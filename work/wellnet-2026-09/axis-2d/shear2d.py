def tap(query, retries=4):
    body = urllib.parse.urlencode({"REQUEST": "doQuery", "LANG": "ADQL",
                                   "FORMAT": "csv", "QUERY": query}).encode()
    for k in range(retries):
        try:
            req = urllib.request.Request(TAP, data=body,
                                         headers={"User-Agent": UA})
            with urllib.request.urlopen(req, timeout=300, context=CTX) as r:
                return r.read()
        except Exception:                                       # noqa: BLE001
            if k == retries - 1:
                raise
            time.sleep(3 * (k + 1))


def parse_csv(raw):
    import pandas as pd
    df = pd.read_csv(io.BytesIO(raw))
    return list(df.columns), df.to_numpy(dtype=float)


def phi_west(ra_s, de_s, ra_c, de_c):
    d2r = math.pi / 180.0
    dra = (ra_s - ra_c) * math.cos(de_c * d2r)
    dde = de_s - de_c
    return np.arctan2(dde, -dra), np.hypot(dra, dde) * d2r


# ------------------------------------------------------- per-cluster harmonics
def harmonics(e, w, R, phi_rel, edges, resp):
    """Weighted least squares of e(phi) = a0 + a2c cos2phi + a2s sin2phi.

    Done per radial bin with the actual azimuthal coverage in the design, so a
    cluster near a mask edge is handled exactly rather than by assuming
    <cos^2 2phi> = 1/2.  Errors come from the WLS covariance with shape-noise
    weights; the full 3x3 covariance is returned so the monopole-quadrupole
    noise correlation can be inspected instead of assumed to vanish.
    """
    out = []
    for i in range(len(edges) - 1):
        m = (R >= edges[i]) & (R < edges[i + 1])
        n = int(m.sum())
        if n < 30:
            out.append(None)
            continue
        c2 = np.cos(2 * phi_rel[m])
        s2 = np.sin(2 * phi_rel[m])
        X = np.column_stack([np.ones(n), c2, s2])
        ww = w[m]
        y = e[m]
        XtW = X.T * ww
        A = XtW @ X
        try:
            Ainv = np.linalg.inv(A)
        except np.linalg.LinAlgError:
            out.append(None)
            continue
        beta = Ainv @ (XtW @ y)
        # shape-noise covariance: sum_j w_j^2 sigma_j^2 x_j x_j^T, with
        # sigma_j^2 estimated by the weighted variance of e in the bin
        var = float(np.sum(ww * (y - X @ beta) ** 2) / max(np.sum(ww), 1e-30))
        cov = Ainv @ ((X.T * (ww ** 2 * var)) @ X) @ Ainv
        r = resp[i] if resp[i] and abs(resp[i]) > 1e-3 else np.nan
        out.append(dict(n=n, R=float(np.sum(ww * R[m]) / np.sum(ww)),
                        a0=float(beta[0]) / r, a2c=float(beta[1]) / r,
                        a2s=float(beta[2]) / r,
                        e0=float(math.sqrt(max(cov[0, 0], 0))) / abs(r),
                        e2c=float(math.sqrt(max(cov[1, 1], 0))) / abs(r),
                        e2s=float(math.sqrt(max(cov[2, 2], 0))) / abs(r),
                        rho_0_2s=float(cov[0, 2]
                                       / math.sqrt(max(cov[0, 0] * cov[2, 2],
                                                       1e-300))),
                        R_metacal=float(r)))
    return out


def cluster_measure(rec, raw, edges_mpc):
    """Everything measurable from one cluster's background sources."""
    head, a = parse_csv(raw)
    if a.shape[0] < 200:
        return None
    col = {n: i for i, n in enumerate(head)}
    ra, de = a[:, col["ra"]], a[:, col["dec"]]
    e1, e2 = a[:, col["mcal_g_1_noshear"]], a[:, col["mcal_g_2_noshear"]]
    w = a[:, col["mcal_w_noshear"]]
    zs = a[:, col["dnf_z"]]
    e1p, e1m = a[:, col["mcal_g_1_1p"]], a[:, col["mcal_g_1_1m"]]
    e2p, e2m = a[:, col["mcal_g_2_2p"]], a[:, col["mcal_g_2_2m"]]
    z_l = rec["z"]
    phi, th = phi_west(ra, de, rec["RA"], rec["DE"])
    Rphys = th * rec["DA"] / P.MPC
    bg = (zs > z_l + DZ_BG) & (Rphys >= edges_mpc[0]) & (Rphys < edges_mpc[-1])
    if bg.sum() < 200:
        return None
    c2, s2 = np.cos(2 * phi), np.sin(2 * phi)
    et = -(e1 * c2 + e2 * s2)
    ex = (e1 * s2 - e2 * c2)
    # metacalibration response per radial bin
    resp = []
    for i in range(len(edges_mpc) - 1):
        m = bg & (Rphys >= edges_mpc[i]) & (Rphys < edges_mpc[i + 1])
        if m.sum() < 30:
            resp.append(np.nan)
            continue
        ww = w[m]
        sw = ww.sum()
        R11 = float(np.sum(ww * (e1p[m] - e1m[m])) / sw / (2 * DGAMMA))
        R22 = float(np.sum(ww * (e2p[m] - e2m[m])) / sw / (2 * DGAMMA))
        resp.append(0.5 * (R11 + R22))
    beta_s = np.where(zs > z_l, (P.d_com(zs) - P.d_com(z_l)) / (1.0 + zs)
                      / np.maximum(P.d_ang(zs), 1.0), 0.0)
    return dict(phi=phi[bg], R=Rphys[bg], et=et[bg], ex=ex[bg], w=w[bg],
                e1=e1[bg], e2=e2[bg], resp=resp,
                beta=float(np.sum(w[bg] * beta_s[bg]) / np.sum(w[bg])),
                beta2=float(np.sum(w[bg] * beta_s[bg] ** 2) / np.sum(w[bg])),
                n=int(bg.sum()))


# ------------------------------------------------- predicted monopole, no slip
def predicted_monopole(rec, R_mpc, beta, beta2):
    """g_+(R) from baryons + RAR under NO SLIP -- never from the shear itself.

    This is the column the phase statistic is regressed on, so it must not
    share any noise with the measurement.  It comes from the Bahar+2022
    Vikhlinin electron-density fit only.
    """
    sysm = P.System(rec, f_star=F_STAR)
    Rm = np.asarray(R_mpc) * P.MPC
    g = sysm.g_pred(law="rar")
    S, dS = sysm.sigma_profile(g, Rm, r_trunc_mpc=10.0)
    scr = P.CLIGHT ** 2 / (4.0 * math.pi * P.G * rec["DA"] * max(beta, 1e-6))
    kap, gam = S / scr, dS / scr
    corr = 1.0 + kap * (beta2 / max(beta, 1e-9) ** 2 - 1.0)
    return gam / np.maximum(1.0 - kap, 1e-3) * corr


# ----------------------------------------------------------------- the global fit
def fit_alpha(rows, key="a2s", use_pred=True, sin2d=None,
              with_sin2d=True, fixed_effects=False):
    """WLS for alpha, beta, gamma over every (cluster, radial bin).

    `key` selects the channel:
        a2s  the PHASE-MISALIGNED channel -- zero for any source-axis model,
             including a mis-deprojected triaxial baryon distribution.  This
             is the test.
        a2c  the source-aligned channel -- a positive control: elliptical
             baryons must produce a signal here.
        x2s  the same misaligned channel of the CROSS component, a B-mode
             null that no lensing signal can produce.

    `sin2d`, if given, replaces the measured sin 2Delta per cluster.  That is
    the null: randomising the EXTERNAL axis destroys the only thing the
    hypothesis is about while leaving every property of the shear -- its
    noise, its mask, its radial profile, its systematics -- exactly as
    measured.
    """
    ekey = {"a2s": "e2s", "a2c": "e2c", "x2s": "e2s"}[key]
    nc = len(rows)
    X, y, wgt = [], [], []
    for k, r in enumerate(rows):
        sd = (r["sin2delta"] if sin2d is None else float(sin2d[k]))             if with_sin2d else 1.0
        for b in r["bins"]:
            if b is None:
                continue
            v = b.get(key, np.nan)
            e = b.get(ekey, np.nan)
            if not np.isfinite(v) or not np.isfinite(e) or e <= 0:
                continue
            gp = b["g_pred"] if use_pred else b["a0"]
            if not np.isfinite(gp):
                continue
            if fixed_effects:
                # one intercept per cluster.  sin 2Delta is constant within a
                # cluster, so the uniform-shear column and every other
                # per-cluster systematic are absorbed exactly, and alpha is
                # identified ONLY by the RADIAL variation of g_pred inside each
                # object -- the standing brief's "system fixed effects".
                row = [sd * gp] + [0.0] * nc
                row[1 + k] = 1.0
            elif with_sin2d:
                row = [sd * gp, sd, 1.0]
            else:
                # no sin 2Delta factor: the source-aligned positive control,
                # where the baryonic quadrupole scales with the monopole and
                # NOT with the axis misalignment.  The sin 2Delta column would
                # be identical to the intercept here, so it is dropped rather
                # than left to make the normal equations singular.
                row = [gp, 1.0]
            X.append(row)
            y.append(v)
            wgt.append(1.0 / e ** 2)
    if len(y) < 8 + (nc if fixed_effects else 0):
        return None
    X = np.array(X)
    y = np.array(y)
    W = np.array(wgt)
    A = (X.T * W) @ X
    try:
        Ainv = np.linalg.inv(A)
    except np.linalg.LinAlgError:
        return None
    b = Ainv @ ((X.T * W) @ y)
    resid = y - X @ b
    chi2 = float(np.sum(W * resid ** 2))
    out = dict(alpha=float(b[0]),
               e_alpha=float(math.sqrt(max(Ainv[0, 0], 0))),
               chi2=chi2, dof=len(y) - X.shape[1], n=len(y),
               n_param=int(X.shape[1]))
    if not fixed_effects and with_sin2d:
        out.update(beta=float(b[1]), gamma=float(b[2]),
                   e_beta=float(math.sqrt(max(Ainv[1, 1], 0))),
                   e_gamma=float(math.sqrt(max(Ainv[2, 2], 0))),
                   corr_alpha_beta=float(Ainv[0, 1]
                                         / math.sqrt(max(Ainv[0, 0]
                                                         * Ainv[1, 1],
                                                         1e-300))))
    return out


def randomised_axes(rows, rng):
    """sin 2Delta with the EXTERNAL position angle drawn uniformly at random."""
    return np.array([math.sin(2 * (rng.uniform(0, math.pi)
                                   - math.radians(r["pa_mem_deg"])))
                     for r in rows])


