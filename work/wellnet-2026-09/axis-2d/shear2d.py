"""JOB 2 -- THE TWO-DIMENSIONAL SHEAR TEST.  Amplitude AND phase.

Azimuthally averaging a shear field throws away almost all of its directional
content.  That is why the eFEDS lane, which is the right instrument for the
scalar question, cannot settle the tensor one: g_t(R) is a single number per
radius and a tensor, a triaxial baryon distribution and a deprojection error
all move it the same way.

The two-dimensional field does not have that problem, because the PHASE of the
shear quadrupole is an independent observable, and the three hypotheses put it
in different places:

    scalar gravity, whatever its form, and a mis-deprojected TRIAXIAL BARYON
        distribution, both put the quadrupole along the BARYONIC axis.  In a
        frame aligned with that axis they produce cos 2phi and NOTHING in
        sin 2phi.
    a tensor aligned with an EXTERNAL tidal axis puts a quadrupole at the
        external angle.  Decomposed in the source-aligned frame,

            Q(phi) = a_src cos 2phi + a_ext cos 2(phi - Delta)
                   = [a_src + a_ext cos 2Delta] cos 2phi
                     + [a_ext sin 2Delta] sin 2phi

        so the sin 2phi coefficient in the source-aligned frame is a PURE
        external-axis signature with a predicted sign, set by the measured
        misalignment Delta between the two independently measured axes.

THE STATISTIC.  For cluster i and radial bin b, in the frame aligned with the
member-light axis,

    A_s(i, b) = alpha * sin2Delta_i * g_pred(i, b)          <- the tensor
              + beta  * sin2Delta_i                          <- uniform shear
              + gamma                                        <- additive c-term

alpha is the headline.  The three columns are separated by their RADIAL
dependence: a real tensor quadrupole scales with the cluster's own shear
signal, which falls steeply with R, while a uniform shear leaking in from a
neighbouring cluster is R-independent -- and a neighbour's uniform shear is
aligned with the external axis BY CONSTRUCTION, so it is the one systematic
that mimics this signal exactly.  It is a fitted column, not a footnote.

WHY g_pred AND NOT THE MEASURED MONOPOLE.  Regressing a measured quadrupole on
a measured monopole from the SAME sources puts the same noise on both axes.
This programme retracted rho_p = -0.304 for exactly that.  So the design
column is the monopole PREDICTED from the baryons (the Bahar+2022 Vikhlinin
density fit) through the RAR under no slip -- a quantity the shear catalogue
never touches.  The measured-monopole version is computed alongside and its
noise correlation with A_s is reported.

CALIBRATION.  alpha's null is generated by RANDOMISING THE EXTERNAL AXIS: the
member-light angle, and therefore every measured harmonic, is left exactly as
it is, while the external position angle is redrawn uniformly, and the fit is
rerun 4000 times.  That preserves every property of the shear data -- its
noise, its masks, its systematics, its radial profile, its baryonic quadrupole
-- and destroys only the thing the hypothesis is about.  The p value is read
off that distribution, not from a chi-squared.

THREE CHANNELS ARE FITTED, NOT ONE.
    a2s   the phase-misaligned channel -- THE TEST.
    a2c   the source-aligned channel -- a POSITIVE CONTROL.  Elliptical
          baryons must show up here, and if they do not, the machinery is not
          measuring a quadrupole at all and a null in a2s means nothing.
    x2s   the same channel of the CROSS component -- a B-mode null that no
          lensing signal of any kind can produce.
and the whole thing is repeated on a near-round NEGATIVE CONTROL sample.

THE SIGN CONVENTION IS MEASURED, NOT ASSUMED.  phi = atan2(d_dec, -d_ra cos
dec): the DECADE/DES ellipticity basis has its first axis pointing WEST.  The
tangential monopole is required to come out POSITIVE as a gate before any
quadrupole is looked at; the other sign choice gives -0.002 instead of +0.011.
"""
