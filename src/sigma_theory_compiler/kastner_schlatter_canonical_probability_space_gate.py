def _validate_result(result: Mapping[str, Any]) -> None:
    if result.get("schema_version") != RESULT_SCHEMA:
        raise ValueError("canonical-probability result schema changed")
    if result.get("decision_counts") != {"pass": 0, "reject": 0, "blocked": 2}:
        raise ValueError("canonical-probability candidate partition changed")
    if result.get("gate_counts") != EXPECTED_COUNTS:
        raise ValueError("canonical-probability gate counts changed")
    construction = result.get("canonical_conditional_construction", {})
    if (
        construction.get("paper_or_QED_supplies_this_probability_space") is not False
        or construction.get("candidate_action_selects_this_probability_space") is not False
        or construction.get("causal_filtration", {}).get("right_continuous") is not True
        or construction.get("causal_filtration", {}).get("complete") is not True
    ):
        raise ValueError("canonical-probability attribution or filtration overclaim")
    controls = result.get("exact_controls", {})
    if (
        controls.get("finite_partition_PGF_positive_control", {}).get("joint_exponent") != "-3"
        or controls.get("centered_increment_martingale_positive_control", {}).get(
            "conditional_centered_increment"
        )
        != "0"
        or controls.get("same_action_Cox_nonidentifiability", {}).get(
            "Cox_variance_at_mu_2"
        )
        != "3"
        or controls.get("same_action_Cox_nonidentifiability", {}).get(
            "Cox_second_factorial_moment_at_mu_2"
        )
        != "5"
    ):
        raise ValueError("canonical-probability exact control changed")
    records = result.get("candidate_records", [])
    if len(records) != 2 or any(
        record.get("candidate_decision") != "blocked"
        or record.get("compiler_canonical_probability_space") != "pass"
        or record.get("compiler_compensator_martingale_identity") != "pass"
        or record.get("paper_or_QED_probability_space_derived") is not False
        or record.get("candidate_action_selects_Poisson_completion") is not False
        or record.get("candidate_action_rejection_authorized") is not False
        for record in records
    ):
        raise ValueError("canonical-probability candidate boundary changed")
    if result.get("first_blocker") != FIRST_BLOCKER:
        raise ValueError("canonical-probability first blocker changed")
    if any(result.get("claim_seals", {}).values()) or any(result.get("data_seals", {}).values()):
        raise ValueError("canonical-probability seal opened")
    if (
        result.get("content_sha256") is not None
        and _content_sha(result) != result["content_sha256"]
    ):
        raise ValueError("canonical-probability content hash mismatch")


