def run_loop(
    *,
    config: LoopConfig | None = None,
    ledger_path: str | Path = "runs/math/funsearch/spend-ledger.json",
    max_calls: int = 800,
    max_dollars_hundredths: int = 1000,
    charge_per_call_hundredths: int = 1,
    proposer_kind: str = "auto",
    claude_executable: str = "claude",
    corpus_database: str | Path = "runs/math/prior-art/cf-corpus-v1.sqlite",
    corpus_manifest: str | Path = "runs/math/prior-art/cf-corpus-v1-manifest.json",
    include_corpus_problem: bool = True,
) -> dict[str, Any]:
    """Run every declared problem and seal one receipt."""

    started = time.perf_counter()
    settings = config or LoopConfig()
    problems = declared_problems()
    if proposer_kind == "mock":
        live_attempt = {"ok": False, "reason": "not_probed", "detail": "proposer_kind=mock"}
        use_live = False
        degraded = False
    else:
        credential = load_api_credential()
        live_attempt = _attempt_live_model(problems["blinded_sequence_rule"], claude_executable)
        live_attempt = dict(live_attempt, credential=credential)
        if not live_attempt["ok"]:
            raise ProposerUnavailable(
                f"requested proposer {proposer_kind!r} is unreachable: "
                f"{live_attempt.get('reason')} / {str(live_attempt.get('detail'))[:200]}.  "
                "There is no degraded mode: a run either has the proposer it declared or it does "
                "not run at all.  Pass proposer_kind='mock' to run the deterministic mutator "
                "deliberately, which is a different experiment and is labelled as one."
            )
        use_live = True
        degraded = False

    corpus = None
    corpus_binding: dict[str, Any] = {"bound": False, "reason": "not requested"}
    if include_corpus_problem:
        try:
            from .cf_prior_art_corpus import load_corpus

            corpus = load_corpus(corpus_database, corpus_manifest)
            corpus_binding = {
                "bound": True,
                "database": str(corpus_database).replace("\\", "/"),
                "records": corpus.manifest["counts"]["records"],
                "seeds": corpus.manifest["counts"]["seeds"],
                "content_sha256": corpus.manifest["content_sha256"],
                "external_fetch_performed": corpus.manifest["claims"]["external_fetch_performed"],
            }
        except Exception as error:  # noqa: BLE001 - a missing corpus degrades, never crashes
            corpus_binding = {"bound": False, "reason": str(error)[:200]}

    governor = SpendGovernor(
        Path(ledger_path), max_calls, max_dollars_hundredths, charge_per_call_hundredths
    )

    def make_proposer(problem: ProblemSpec, salt: int) -> Any:
        if use_live:
            return ClaudeCliProposer(claude_executable)
        return MockMutationProposer(settings.seed + salt, problem.mutation_bank)

    blocks: list[dict[str, Any]] = []
    # Three arms on the response problem, differing in one declared field each:
    #   blinded_response_law              -- search under the anti-recall multiplier
    #   blinded_response_law_free_search  -- the identical search with the grammar emptied
    #   blinded_response_law_control      -- no search; re-scores the live arm's population
    order = [
        (0, "blinded_sequence_rule", "blinded_sequence_rule", (), (), False),
        (1, "blinded_response_law", "blinded_response_law", (), RESPONSE_PROBE_PROGRAMS, False),
        (
            1,  # the same proposer seed as the arm above: only the grammar differs
            "blinded_response_law_free_search",
            "blinded_response_law_control",
            (),
            RESPONSE_PROBE_PROGRAMS,
            False,
        ),
        (
            2,
            "blinded_ratio_expansion",
            "blinded_ratio_expansion",
            EXPANSION_PROBE_PROGRAMS,
            (),
            True,
        ),
    ]
    for salt, label, key, extras, founders, needs_corpus in order:
        if needs_corpus and corpus is None:
            continue
        problem = problems[key]
        block = run_problem(
            problem,
            settings,
            make_proposer(problem, salt * 977),
            governor,
            corpus=corpus if needs_corpus else None,
            extra_programs=extras,
            seeded_programs=founders,
        )
        block["run_label"] = label
        blocks.append(block)

    # The control.  It searches nothing: it re-scores the anti-recall run's *entire* sealed
    # population under a problem that differs in exactly one declared field -- the
    # known-solution grammar is empty.  Same programs, same evaluator, same sandbox, so any
    # score that moves can only have moved because of the multiplier.
    live_block = next(
        (item for item in blocks if item["run_label"] == "blinded_response_law"), None
    )
    if live_block is not None:
        replicas = tuple(
            (record["origin"], record["source"]) for record in live_block["sealed_programs"]
        )
        control_block = run_problem(
            problems["blinded_response_law_control"],
            replace(settings, generations=0),
            make_proposer(problems["blinded_response_law_control"], 3 * 977),
            governor,
            extra_programs=replicas,
        )
        control_block["run_label"] = "blinded_response_law_control"
        control_block["control_note"] = (
            "no search was run here. Every program sealed by the anti-recall run was "
            "re-scored against a problem identical in every declared field except one: "
            "known_solution_grammar is empty."
        )
        blocks.append(control_block)

    hostile = run_hostile_suite()
    body: dict[str, Any] = {
        "schema_version": RECEIPT_SCHEMA,
        "lane": "funsearch-anti-recall",
        "claims": CLAIMS,
        "config": settings.to_dict(),
        "config_sha256": canonical_sha256(settings.to_dict()),
        "proposer": {
            "requested": proposer_kind,
            "used": "claude_cli_oauth" if use_live else "deterministic_mock_mutator",
            "degraded": degraded,
            "live_model_attempt": live_attempt,
            "note": (
                "the proposer supplies source code only; it never scores, ranks, or "
                "adjudicates anything, and every number in this receipt was produced by "
                "executing a program"
            ),
        },
        "prior_art_corpus": corpus_binding,
        "sandbox": {
            "declaration": SandboxBudget().to_dict(),
            "runner_sha256": hashlib.sha256(
                SANDBOX_RUNNER_SOURCE.encode("utf-8")
            ).hexdigest(),
            "hostile_suite": hostile,
            "all_hostile_programs_contained": all(item["contained"] for item in hostile),
            "incident_log": _incident_log(blocks),
        },
        "budget": governor.to_dict(),
        "problems": blocks,
        "headline": _headline(blocks),
        "scope": SCOPE,
    }
    core = canonical_sha256(body)
    body["result_core_sha256"] = core
    body["measurement"] = {"elapsed_seconds": format(time.perf_counter() - started, ".3f")}
    return {**body, "content_sha256": canonical_sha256(body)}


def _incident_log(blocks: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """Every program that failed to execute, counted by typed reason.

    Model output is untrusted, so what matters is not that nothing went wrong but that
    everything that went wrong was *classified*.  A reason outside the declared vocabulary
    would mean the sandbox surprised us, and the receipt validator refuses that.
    """

    counts: dict[str, int] = {}
    total = 0
    for block in blocks:
        for incident in block["sandbox_incidents"]:
            counts[incident["reason"]] = counts.get(incident["reason"], 0) + 1
            total += 1
    return {
        "incidents": total,
        "by_reason": dict(sorted(counts.items())),
        "every_reason_is_declared": all(name in SANDBOX_FAILURE_REASONS for name in counts),
        "loop_survived_every_incident": True,
    }


#: Files searched for ``ANTHROPIC_API_KEY`` when it is not already in the environment, in order.
#: A repository-local ``.env`` wins; ``~/.invariant.env`` is the machine-wide fallback that every
#: worktree shares, so one credential serves all of them and no secret is duplicated per checkout.
CREDENTIAL_FILES: tuple[str, ...] = (".env", "~/.invariant.env")


def load_api_credential(root: str | Path | None = None) -> dict[str, Any]:
    """Put ``ANTHROPIC_API_KEY`` into the environment if a credential file supplies one.

    Returns a typed provenance record naming WHERE the credential came from and a short digest
    of it, never the credential itself.  The digest is enough to tell two keys apart in a receipt
    and is not reversible.  An already-set environment variable always wins and is never
    overwritten.
    """

    existing = os.environ.get("ANTHROPIC_API_KEY", "").strip()
    if existing:
        return {
            "present": True,
            "source": "environment",
            "key_sha256_prefix": hashlib.sha256(existing.encode("utf-8")).hexdigest()[:12],
        }
    base = Path(root) if root is not None else Path(__file__).resolve().parents[2]
    for name in CREDENTIAL_FILES:
        candidate = Path(name).expanduser() if name.startswith("~") else base / name
        if not candidate.is_file():
            continue
        for line in candidate.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            name_part, _, value = line.partition("=")
            if name_part.strip() != "ANTHROPIC_API_KEY":
                continue
            value = value.strip().strip('"').strip("'")
            if not value:
                continue
            os.environ["ANTHROPIC_API_KEY"] = value
            return {
                "present": True,
                "source": str(candidate).replace("\\", "/"),
                "key_sha256_prefix": hashlib.sha256(value.encode("utf-8")).hexdigest()[:12],
            }
    return {"present": False, "source": "none", "key_sha256_prefix": ""}


def _attempt_live_model(problem: ProblemSpec, executable: str) -> dict[str, Any]:
    """Try the local adapter once and record the typed outcome, whatever it is."""

    proposer = ClaudeCliProposer(executable, timeout=120.0)
    seeded = ScoredProgram(
        hashlib.sha256(problem.seed_program.encode("utf-8")).hexdigest(),
        problem.seed_program,
        "seed",
        0,
        0,
        SandboxOutcome(True),
        (),
        0.0,
        {},
        NoveltyVerdict(1.0, "unscored", {}),
        0.0,
    )
    try:
        prompt = build_prompt(problem, (seeded,))
    except FunSearchError as error:
        return {"ok": False, "reason": "prompt_refused", "detail": str(error)[:200]}
    call = proposer.propose(prompt, (seeded,), 1)
    return {
        "ok": call.ok and call.returned > 0,
        "reason": call.reason or ("returned_programs" if call.returned else "returned_nothing"),
        "detail": call.detail[:200],
        "executable": executable,
    }


