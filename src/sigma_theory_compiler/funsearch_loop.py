#: A program at or above this quality is "high quality" for headline purposes.  Declared here
#: rather than chosen per run so the counts in two receipts mean the same thing.
HIGH_QUALITY_THRESHOLD = 0.99


@dataclass(frozen=True, slots=True)
class LoopConfig:
    islands: int = 6
    island_capacity: int = 12
    generations: int = 150
    examples_per_prompt: int = 3
    proposals_per_call: int = 6
    reset_period: int = 12
    temperature: float = 0.12
    seed: int = 20260818

    def to_dict(self) -> dict[str, Any]:
        return {
            "islands": self.islands,
            "island_capacity": self.island_capacity,
            "generations": self.generations,
            "examples_per_prompt": self.examples_per_prompt,
            "proposals_per_call": self.proposals_per_call,
            "reset_period": self.reset_period,
            "temperature": format(self.temperature, ".6g"),
            "seed": self.seed,
        }


def _stable_hash(text: str) -> int:
    """A seed that does not move between processes; ``hash()`` of a str is randomised."""

    return int(hashlib.sha256(text.encode("utf-8")).hexdigest()[:8], 16)


def _sample_examples(
    island: Sequence[ScoredProgram], count: int, temperature: float, rng: random.Random
) -> list[ScoredProgram]:
    """FunSearch's score-weighted sampling: softmax over final_score within one island."""

    if not island:
        return []
    top = max(item.final_score for item in island)
    weights = [math.exp((item.final_score - top) / max(temperature, 1e-9)) for item in island]
    chosen: list[ScoredProgram] = []
    pool = list(island)
    pool_weights = list(weights)
    for _ in range(min(count, len(pool))):
        pick = rng.choices(range(len(pool)), weights=pool_weights, k=1)[0]
        chosen.append(pool.pop(pick))
        pool_weights.pop(pick)
    return chosen


def run_problem(
    problem: ProblemSpec,
    config: LoopConfig,
    proposer: Any,
    governor: SpendGovernor,
    *,
    corpus: Any = None,
    extra_programs: Sequence[tuple[str, str]] = (),
    seeded_programs: Sequence[tuple[str, str]] = (),
) -> dict[str, Any]:
    """One problem, start to finish.  Returns the problem's block of the receipt.

    ``seeded_programs`` enter the initial population and therefore *compete in selection*,
    which is how the receipt can show that novelty is a pressure rather than a report: a
    perfect-quality reproduction sitting in the population with a zero multiplier is almost
    never drawn as an example, while the same program under an empty grammar dominates the
    sampling.  ``extra_programs`` are scored after the search and never influence it.
    """

    rng = random.Random(config.seed ^ _stable_hash(problem.problem_id))
    seeded = score_program(problem, problem.seed_program, origin="seed", corpus=corpus)
    founders = [seeded]
    for label, source in seeded_programs:
        founders.append(score_program(problem, source, origin=label, corpus=corpus))
    islands: list[list[ScoredProgram]] = [list(founders) for _ in range(config.islands)]
    sealed: dict[str, ScoredProgram] = {item.program_sha256: item for item in founders}
    history: list[dict[str, Any]] = []
    calls: list[ProposalCall] = []
    incidents: list[dict[str, Any]] = []
    example_uses: dict[str, int] = {}
    example_slots = 0
    for item in founders:
        if not item.sandbox.ok:
            incidents.append(
                {"program_sha256": item.program_sha256, **item.sandbox.classification()}
            )
    halt_reason = "generations_exhausted"

    for generation in range(config.generations):
        if not governor.may_call():
            halt_reason = governor.halt_reason
            break
        index = generation % config.islands
        examples = _sample_examples(
            islands[index], config.examples_per_prompt, config.temperature, rng
        )
        example_slots += len(examples)
        for item in examples:
            example_uses[item.program_sha256] = example_uses.get(item.program_sha256, 0) + 1
        try:
            prompt = build_prompt(problem, examples)
        except FunSearchError as error:
            calls.append(
                ProposalCall(
                    getattr(proposer, "proposer_id", "unknown"),
                    "",
                    0,
                    0,
                    False,
                    "prompt_refused_forbidden_vocabulary",
                    str(error)[:200],
                )
            )
            continue
        governor.charge()
        call = proposer.propose(prompt, examples, config.proposals_per_call)
        calls.append(call)
        if not call.ok:
            raise ProposerCallFailed(
                f"proposal call failed at generation {generation}, island {index}: "
                f"{call.reason} / {call.detail[:200]}.  Stopping the run rather than continuing "
                "with an empty generation and sealing a receipt that looks like a full campaign."
            )
        produced: list[ScoredProgram] = []
        for source in proposer.programs():
            scored = score_program(
                problem,
                source,
                origin="proposed",
                generation=generation,
                island=index,
                corpus=corpus,
            )
            produced.append(scored)
            sealed.setdefault(scored.program_sha256, scored)
            if not scored.sandbox.ok:
                incidents.append(
                    {"program_sha256": scored.program_sha256, **scored.sandbox.classification()}
                )
        islands[index] = sorted(
            {item.program_sha256: item for item in [*islands[index], *produced]}.values(),
            key=lambda item: (-item.final_score, item.program_sha256),
        )[: config.island_capacity]
        history.append(
            {
                "generation": generation,
                "island": index,
                "examples": [item.program_sha256[:12] for item in examples],
                "proposed": len(produced),
                "accepted_best_final_score": format(
                    max((item.final_score for item in islands[index]), default=0.0), ".9f"
                ),
                "best_quality_in_island": format(
                    max((item.quality for item in islands[index]), default=0.0), ".9f"
                ),
            }
        )
        if config.reset_period and (generation + 1) % config.reset_period == 0:
            islands = _reset_islands(islands, rng)

    for label, source in extra_programs:
        scored = score_program(problem, source, origin=label, corpus=corpus)
        sealed.setdefault(scored.program_sha256, scored)
        if not scored.sandbox.ok:
            incidents.append(
            {"program_sha256": scored.program_sha256, **scored.sandbox.classification()}
        )

    ordered = sorted(
        sealed.values(), key=lambda item: (-item.final_score, -item.quality, item.program_sha256)
    )
    by_quality = sorted(sealed.values(), key=lambda item: (-item.quality, item.program_sha256))
    zeroed = [
        item
        for item in sealed.values()
        if item.novelty.multiplier == 0.0 and item.quality >= HIGH_QUALITY_THRESHOLD
    ]
    discovered_zeroed = [item for item in zeroed if item.origin == "proposed"]
    survivors = [
        item
        for item in sealed.values()
        if item.quality >= HIGH_QUALITY_THRESHOLD and item.novelty.multiplier > 0.0
    ]
    return {
        "problem": problem.to_dict(),
        "sealed_answer_sha256": canonical_sha256(SEALED_ANSWERS[problem.problem_id]),
        "sealed_answer_revealed_after_scoring": SEALED_ANSWERS[problem.problem_id],
        "loop": config.to_dict(),
        "generations_run": len(history),
        "halt_reason": halt_reason,
        "population_history": history,
        "proposal_calls": [item.to_dict() for item in calls],
        "sandbox_incidents": incidents,
        "sealed_programs": [item.to_dict() for item in ordered],
        "example_sampling": _example_sampling(sealed, example_uses, example_slots),
        "headline": {
            "programs_sealed": len(sealed),
            "high_quality_threshold": format(HIGH_QUALITY_THRESHOLD, ".6g"),
            "best_by_final_score": _brief(ordered[0]) if ordered else None,
            "best_by_quality": _brief(by_quality[0]) if by_quality else None,
            "high_quality_programs": sum(
                1 for item in sealed.values() if item.quality >= HIGH_QUALITY_THRESHOLD
            ),
            "high_quality_zeroed_by_novelty": len(zeroed),
            "high_quality_zeroed_that_the_loop_itself_found": len(discovered_zeroed),
            "high_quality_survivors_of_the_multiplier": len(survivors),
            "zeroed_reasons": sorted({item.novelty.reason for item in zeroed}),
            "best_loop_discovered_rediscovery": (
                _brief(max(discovered_zeroed, key=lambda item: item.quality))
                if discovered_zeroed
                else None
            ),
        },
    }


def _example_sampling(
    sealed: Mapping[str, ScoredProgram], uses: Mapping[str, int], slots: int
) -> dict[str, Any]:
    """How often each planted reproduction was actually drawn as an example.

    This is the number that separates a selection *pressure* from a post-check.  A program
    that is only flagged after the fact keeps being shown to the proposer; a program whose
    score has been multiplied to zero stops being shown, and this counts that.
    """

    rows = [
        {
            "origin": item.origin,
            "quality": format(item.quality, ".9f"),
            "novelty_multiplier": format(item.novelty.multiplier, ".9f"),
            "times_drawn_as_an_example": uses.get(digest, 0),
        }
        for digest, item in sealed.items()
        if item.origin.startswith("probe_known")
    ]
    rows.sort(key=lambda row: (row["origin"],))
    return {
        "example_slots_filled": slots,
        "known_reproductions_in_the_population": len(rows),
        "times_a_known_reproduction_was_drawn": sum(
            row["times_drawn_as_an_example"] for row in rows
        ),
        "rows": rows,
    }


def _reset_islands(
    islands: list[list[ScoredProgram]], rng: random.Random
) -> list[list[ScoredProgram]]:
    """FunSearch's island reset: the weakest half is reseeded from the strongest half."""

    ranked = sorted(
        range(len(islands)),
        key=lambda index: -max((item.final_score for item in islands[index]), default=0.0),
    )
    strong = ranked[: max(1, len(islands) // 2)]
    weak = ranked[max(1, len(islands) // 2) :]
    for index in weak:
        donor = islands[rng.choice(strong)]
        if donor:
            islands[index] = [max(donor, key=lambda item: item.final_score)]
    return islands


def _brief(item: ScoredProgram) -> dict[str, Any]:
    return {
        "program_sha256": item.program_sha256,
        "origin": item.origin,
        "source": item.source,
        "quality": format(item.quality, ".9f"),
        "novelty_multiplier": format(item.novelty.multiplier, ".9f"),
        "novelty_reason": item.novelty.reason,
        "final_score": format(item.final_score, ".9f"),
    }


