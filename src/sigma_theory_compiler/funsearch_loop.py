@dataclass(frozen=True, slots=True)
class ProblemSpec:
    """A problem: a signature, a weak seed, a mechanical evaluator, and a novelty channel.

    The model sees ``signature_text``, ``entry`` and the seed program.  It does not see
    ``evaluator_id``'s hidden data, the problem's real subject, or any target value.
    """

    problem_id: str
    entry: str
    signature_text: str
    seed_program: str
    evaluator_id: str
    probe_points: tuple[float, ...]
    novelty_channel: str
    forbidden_vocabulary: tuple[str, ...]
    sandbox: SandboxBudget
    novelty_policy: NoveltyPolicy = field(default_factory=NoveltyPolicy)
    known_solution_grammar: tuple[KnownFamily, ...] = ()
    mutation_bank: tuple[str, ...] = ()
    output_width: int = 1
    takes_point_argument: bool = True

    def __post_init__(self) -> None:
        if self.novelty_channel not in ("known_solution_grammar", "prior_art_corpus"):
            raise FunSearchError(f"undeclared novelty channel: {self.novelty_channel}")
        if self.evaluator_id not in EVALUATORS:
            raise FunSearchError(f"undeclared evaluator: {self.evaluator_id}")
        leaks = vocabulary_violations(self.seed_program, self.forbidden_vocabulary)
        if leaks:
            raise FunSearchError(f"seed program leaks forbidden vocabulary: {leaks}")
        leaks = vocabulary_violations(self.signature_text, self.forbidden_vocabulary)
        if leaks:
            raise FunSearchError(f"signature leaks forbidden vocabulary: {leaks}")

    def sandbox_inputs(self) -> tuple[tuple[float, ...], ...]:
        if not self.takes_point_argument:
            return ((),)
        return tuple((point,) for point in self.probe_points)

    def to_dict(self) -> dict[str, Any]:
        return {
            "problem_id": self.problem_id,
            "entry": self.entry,
            "signature_text": self.signature_text,
            "seed_program": self.seed_program,
            "evaluator_id": self.evaluator_id,
            "probe_points": [format(item, ".17g") for item in self.probe_points],
            "novelty_channel": self.novelty_channel,
            "novelty_policy": self.novelty_policy.to_dict(),
            "known_solution_grammar": [item.to_dict() for item in self.known_solution_grammar],
            "forbidden_vocabulary": list(self.forbidden_vocabulary),
            "sandbox": self.sandbox.to_dict(),
            "mutation_bank": list(self.mutation_bank),
            "output_width": self.output_width,
        }


# --- The sealed answers.  Nothing on the prompt path may read this table. -------------


def _sealed_sequence_targets() -> tuple[int, ...]:
    """The hidden rule for the blinded sequence problem: 3n^2 + 2n + 1 + (n mod 4)."""

    return tuple(3 * n * n + 2 * n + 1 + (n % 4) for n in range(48))


def _sealed_response_targets(points: Sequence[float]) -> tuple[float, ...]:
    """The hidden law for the blinded response problem: the MOND simple-nu branch at a=1.2e-10."""

    return tuple(_mond_simple_nu(1.2e-10, point) for point in points)


SEALED_ANSWERS: dict[str, Any] = {
    "blinded_sequence_rule": "3*n*n + 2*n + 1 + (n % 4)",
    "blinded_response_law": "y = (u/2)*(1 + sqrt(1 + 4a/u)), a = 1.2e-10",
    "blinded_ratio_expansion": "target constant e",
}

#: The response problem spans six decades, so its quality and its novelty distance are
#: both measured scale-free.  With a plain relative RMS the identity program scores
#: 0.9996 because the largest decade swamps the rest, which would make the problem
#: undiscriminating and the novelty distances meaningless.
RESPONSE_METRIC = "log_relative_rms"

RESPONSE_POINTS: tuple[float, ...] = tuple(
    10.0 ** (-12.0 + 0.25 * index) for index in range(25)
)
SEQUENCE_FIT_POINTS: tuple[float, ...] = tuple(float(n) for n in range(32))
SEQUENCE_HOLDOUT_POINTS: tuple[float, ...] = tuple(float(n) for n in range(32, 48))


# --- Evaluators.  Deterministic, mechanical, and never shown to the model. -------------


def _evaluate_sequence(problem: ProblemSpec, outputs: Sequence[str]) -> dict[str, Any]:
    """Exact credit for an exact term, graded credit otherwise, so the score is climbable.

    A pure exact-match count is the natural way to state this problem and a terrible way to
    search it: every wrong program scores the same, so there is no gradient to follow.  The
    declared score keeps exactness as the only route to 1.0 and hands out relative partial
    credit below that, which is what makes the search a search.
    """

    targets = _sealed_sequence_targets()
    matched = 0
    total_score = 0.0
    for index, raw in enumerate(outputs):
        value = float(raw)
        target = targets[index]
        if abs(value) < 1e15 and round(value) == target:
            matched += 1
            total_score += 1.0
            continue
        total_score += 1.0 / (1.0 + abs(value - target) / (1.0 + abs(target)))
    total = len(outputs)
    return {
        "quality": total_score / total if total else 0.0,
        "detail": {"exact_terms": matched, "of": total},
    }


def _evaluate_response(problem: ProblemSpec, outputs: Sequence[str]) -> dict[str, Any]:
    targets = _sealed_response_targets(problem.probe_points)
    values = [float(item) for item in outputs]
    distance = distance_between(RESPONSE_METRIC, targets, values)
    quality = 0.0 if not math.isfinite(distance) else max(0.0, 1.0 - distance)
    return {
        "quality": quality,
        "detail": {"metric": RESPONSE_METRIC, "distance": format(distance, ".6g")},
    }


def _evaluate_ratio_expansion(problem: ProblemSpec, outputs: Sequence[str]) -> dict[str, Any]:
    """Digits of agreement between the induced continued fraction and the hidden constant."""

    coefficients = _coefficients_from_outputs(outputs)
    if coefficients is None:
        return {"quality": 0.0, "detail": {"reason": "coefficients_out_of_declared_range"}}
    value = _continued_fraction_value(coefficients)
    if value is None:
        return {"quality": 0.0, "detail": {"reason": "did_not_converge"}}
    target = math.e
    error = abs(value - target) / max(1.0, abs(target))
    digits = 0.0 if error <= 0.0 else -math.log10(error)
    digits = 30.0 if error <= 0.0 else max(0.0, min(30.0, digits))
    return {
        "quality": digits / 30.0,
        "detail": {"matched_digits": format(digits, ".3f"), "cf_value": format(value, ".12g")},
    }


EVALUATORS: dict[str, Callable[[ProblemSpec, Sequence[str]], dict[str, Any]]] = {
    "exact_match_fraction": _evaluate_sequence,
    "bounded_relative_accuracy": _evaluate_response,
    "digits_of_agreement": _evaluate_ratio_expansion,
}


def _coefficients_from_outputs(outputs: Sequence[str]) -> tuple[tuple[int, ...], ...] | None:
    """Read a program's eight emitted numbers as two ascending integer coefficient vectors."""

    if len(outputs) != 8:
        return None
    values: list[int] = []
    for raw in outputs:
        number = float(raw)
        if abs(number) > 64 or number != round(number):
            return None
        values.append(round(number))
    alpha = tuple(values[:4])
    beta = tuple(values[4:])
    if all(item == 0 for item in alpha) or all(item == 0 for item in beta):
        return None
    return alpha, beta


def _continued_fraction_value(coefficients: tuple[tuple[int, ...], ...], depth: int = 200):
    """``a_0 + b_1/(a_1 + b_2/(a_2 + ...))`` evaluated backwards, or ``None`` if it degenerates."""

    alpha, beta = coefficients

    def _horner(vector: Sequence[int], index: int) -> float:
        total = 0.0
        for coefficient in reversed(vector):
            total = total * index + coefficient
        return total

    def a_at(index: int) -> float:
        return _horner(alpha, index)

    def b_at(index: int) -> float:
        return _horner(beta, index)

    x = a_at(depth)
    for index in range(depth - 1, -1, -1):
        if x == 0.0:
            return None
        x = a_at(index) + b_at(index + 1) / x
        if not math.isfinite(x):
            return None
    return x


