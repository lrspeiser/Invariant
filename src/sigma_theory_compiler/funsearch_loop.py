"""A FunSearch-style proposal loop whose selection pressure penalises recall.

The failure this is built against is concrete.  Asked about galaxy rotation, a language
model "rediscovered" MOND -- it wrote out a rearrangement of a formula it had read, and the
rearrangement looked like a derivation.  Nothing in the exchange could tell the two apart,
because the model was asked for an *answer* and answers are exactly what recall produces.

DeepMind's FunSearch (Nature, 2023) supplies the first half of the fix: never ask the model
for an answer, ask it for a **program**, then execute the program and score it mechanically.
The model's reasoning, confidence and prose are discarded; only the measured score survives.
A model cannot recall its way to a good score on an evaluator it has never seen.

That alone is not enough here.  A model that recalls MOND can still write a *program* that
computes MOND, and on data generated by MOND that program scores brilliantly.  So this module
adds the second half:

**final_score = quality_score * novelty_multiplier**, with the multiplier computed
mechanically, before selection, from the program's *behaviour*:

* **corpus channel** -- the program's induced closed form is screened against the prior-art
  corpus by :mod:`.cf_prior_art_screen`, including its equivalence-orbit test.  Verdict
  ``KNOWN`` -> multiplier ``0.0``.  Reproducing a catalogued formula scores zero no matter how
  well it fits.
* **grammar channel** -- the problem declares a KNOWN-SOLUTION GRAMMAR: a list of known
  families with free parameters.  Each family is best-fitted to the candidate's own outputs
  and the normalised RMS deviation is measured.  Deviation at or below the declared zero
  threshold -> multiplier ``0.0``.  Because the comparison is behavioural, an *algebraic
  rewrite* of a known formula is caught: a fixed-point iteration, a bisection root-find and a
  rationalised radical are different programs with identical behaviour, and identical
  behaviour is what the test measures.
* **otherwise** -- the multiplier scales linearly with the measured distance to the nearest
  known family, saturating at a declared distance.

Novelty is therefore a *selection pressure*, not a post-check: it multiplies the score that
decides which programs are sampled as examples for the next round, so the search is steered
away from the known basin while it runs.  Every candidate records its quality, its multiplier
and **why the multiplier was what it was**, so "it just rediscovered the known answer" is a
logged event with a named cause rather than a silent success.

**The model is kept blind.**  It never sees the problem's domain name, any physics or
mathematics vocabulary beyond the bare signature, or any target value.  A vocabulary guard
(the idiom from :mod:`.blind_planetary_law_rediscovery_campaign`) tokenises the assembled
prompt and refuses to send it if a declared forbidden term appears -- including a term that
entered through a *program's own variable names*, which is the realistic leak.

**Programs are untrusted.**  They are model output, so they run in a subprocess with a
static AST screen, restricted builtins, a declared import allowlist, a hard wall-clock
timeout and a memory cap.  Every failure is a typed reason attached to the candidate; a
program that loops forever, allocates without bound, imports something undeclared or tries to
touch the filesystem is scored as a failure and the loop continues.

**Honest limits.**  ``corpus_absence_establishes_novelty`` is sealed ``false``: a nonzero
multiplier means "not within the declared grammar and not in this finite corpus", never
"new".  And on a problem whose data really was generated by a known law, the honest outcome
is that every high-quality program is a rewrite of that law and every one of them scores
zero.  That is the mechanism working, and the receipt reports it as such.
"""

