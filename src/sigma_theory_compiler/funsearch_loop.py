@dataclass(frozen=True, slots=True)
class SandboxBudget:
    """The declared execution envelope.  Everything outside it is a typed failure."""

    wall_seconds: float = 4.0
    memory_bytes: int = 512 * 1024 * 1024
    import_allowlist: tuple[str, ...] = ("math",)
    network: bool = False
    filesystem: bool = False

    def __post_init__(self) -> None:
        if not 0.05 <= float(self.wall_seconds) <= 120.0:
            raise FunSearchError("sandbox wall_seconds outside the declared envelope")
        if not 1_000_000 <= int(self.memory_bytes) <= 4 * 1024**3:
            raise FunSearchError("sandbox memory_bytes outside the declared envelope")
        if self.network or self.filesystem:
            raise FunSearchError("sandbox network and filesystem access are not declarable")
        if tuple(sorted(set(self.import_allowlist))) != tuple(self.import_allowlist):
            raise FunSearchError("import allowlist must be unique and sorted")

    def to_dict(self) -> dict[str, Any]:
        return {
            "wall_seconds": format(float(self.wall_seconds), ".6g"),
            "memory_bytes": int(self.memory_bytes),
            "import_allowlist": list(self.import_allowlist),
            "network": False,
            "filesystem": False,
            "builtins_allowlist": list(BUILTIN_ALLOWLIST),
            "name_denylist": list(NAME_DENYLIST),
        }


@dataclass(frozen=True, slots=True)
class SandboxOutcome:
    """One execution.  ``ok`` programs carry outputs; the rest carry a typed reason."""

    ok: bool
    outputs: tuple[str, ...] = ()
    reason: str = ""
    detail: str = ""
    elapsed_seconds: float = 0.0

    def classification(self) -> dict[str, Any]:
        """The reproducible part: what happened, with no wall-clock measurement in it.

        Timing belongs in an aggregate measurement block, never inside a sealed per-program
        record -- a receipt whose scores replay exactly but whose bytes never do is a receipt
        nobody can check.
        """

        return {"ok": self.ok, "reason": self.reason, "detail": self.detail}

    def to_dict(self) -> dict[str, Any]:
        return {**self.classification(), "elapsed_seconds": format(self.elapsed_seconds, ".3f")}


def static_screen(source: str, import_allowlist: Sequence[str]) -> list[str]:
    """Denials raised by the pre-compile screen, sorted.  Empty means the source may run.

    The screen is the first of five independent layers, and it exists to remove the escapes a
    restricted-builtins jail cannot see: attribute walks through ``__class__``/``__globals__``,
    undeclared imports, and the ``eval``/``getattr`` family.
    """

    allowed = set(import_allowlist)
    try:
        tree = ast.parse(source)
    except SyntaxError as error:
        return [f"syntax_error:{error.msg}"]
    denials: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.split(".")[0] not in allowed:
                    denials.add(f"import_denied:{alias.name}")
        elif isinstance(node, ast.ImportFrom):
            root = (node.module or "").split(".")[0]
            if root not in allowed or node.level:
                denials.add(f"import_denied:{node.module or '.'}")
        elif isinstance(node, ast.Attribute):
            if node.attr.startswith("_"):
                denials.add(f"private_attribute:{node.attr}")
        elif isinstance(node, ast.Name):
            if node.id in NAME_DENYLIST:
                denials.add(f"denied_name:{node.id}")
        elif isinstance(node, ast.Constant):
            if isinstance(node.value, str) and "__" in node.value:
                denials.add("dunder_string_literal")
        elif isinstance(node, (ast.AsyncFunctionDef, ast.Await, ast.AsyncFor, ast.AsyncWith)):
            denials.add("async_construct")
        elif isinstance(node, (ast.Global, ast.Nonlocal)):
            denials.add("scope_escape")
    return sorted(denials)


