# 13. Receipt validation
# ---------------------------------------------------------------------------


def validate_receipt(value: Mapping[str, Any]) -> None:
    """Seals, claims, the arithmetic of every score, and the two run-aborting controls."""

    if value.get("schema_version") != RECEIPT_SCHEMA:
        raise FunSearchError("receipt schema changed")
    body = {key: item for key, item in value.items() if key != "content_sha256"}
    if value.get("content_sha256") != canonical_sha256(body):
        raise FunSearchError("receipt seal changed")
    core_body = {
        key: item
        for key, item in value.items()
        if key not in {"content_sha256", "result_core_sha256", "measurement"}
    }
    if value.get("result_core_sha256") != canonical_sha256(core_body):
        raise FunSearchError("deterministic core seal changed")
    if value.get("claims") != CLAIMS:
        raise FunSearchError("claims block changed")
    if value.get("config_sha256") != canonical_sha256(value.get("config", {})):
        raise FunSearchError("config binding changed")
    if not value["sandbox"]["all_hostile_programs_contained"]:
        raise FunSearchError("a hostile program escaped the sandbox")
    if len(value["sandbox"]["hostile_suite"]) != len(HOSTILE_PROGRAMS):
        raise FunSearchError("hostile suite population changed")
    for item in value["sandbox"]["hostile_suite"]:
        if item["reason"] not in SANDBOX_FAILURE_REASONS:
            raise FunSearchError(f"hostile program produced an untyped reason: {item['reason']}")
    if not value["sandbox"]["incident_log"]["every_reason_is_declared"]:
        raise FunSearchError("a sandbox incident carried a reason outside the declared vocabulary")

    labels = [block["run_label"] for block in value["problems"]]
    required = {
        "blinded_response_law",
        "blinded_response_law_control",
        "blinded_response_law_free_search",
    }
    missing = sorted(required - set(labels))
    if missing:
        raise FunSearchError(f"the anti-recall run is missing declared arms: {missing}")
    unknown = sorted(set(labels) - set(RUN_LABEL_PROBLEM))
    if unknown:
        raise FunSearchError(f"receipt carries undeclared run labels: {unknown}")
    for block in value["problems"]:
        for record in block["sealed_programs"]:
            quality = float(record["quality"])
            multiplier = float(record["novelty"]["novelty_multiplier"])
            final = float(record["final_score"])
            if abs(quality * multiplier - final) > 5e-9:
                raise FunSearchError(
                    f"final_score is not quality * multiplier: {record['program_sha256']}"
                )
            if not record["novelty"]["reason"]:
                raise FunSearchError(
                    f"a candidate carries no novelty reason: {record['program_sha256']}"
                )
            if multiplier == 0.0 and final != 0.0:
                raise FunSearchError("a zeroed candidate kept a nonzero score")
    _validate_anti_recall_control(value)


def _validate_anti_recall_control(value: Mapping[str, Any]) -> None:
    """The control is run-aborting: emptying the grammar must move the multiplier, not quality."""

    by_label = {block["run_label"]: block for block in value["problems"]}
    live = {
        record["program_sha256"]: record
        for record in by_label["blinded_response_law"]["sealed_programs"]
    }
    control = {
        record["program_sha256"]: record
        for record in by_label["blinded_response_law_control"]["sealed_programs"]
    }
    shared = sorted(set(live) & set(control))
    if not shared:
        raise FunSearchError("the control run shares no program with the live run")
    moved = 0
    for digest in shared:
        if live[digest]["quality"] != control[digest]["quality"]:
            raise FunSearchError(
                f"the control changed a quality score, so it does not isolate novelty: {digest}"
            )
        if live[digest]["novelty"]["novelty_multiplier"] != control[digest]["novelty"][
            "novelty_multiplier"
        ]:
            moved += 1
    if not moved:
        raise FunSearchError("the control moved no multiplier, so the grammar had no effect")
    free = next(
        (
            block
            for block in value["problems"]
            if block["run_label"] == "blinded_response_law_free_search"
        ),
        None,
    )
    if free is None:
        raise FunSearchError("the free-search arm is absent")
    if free["problem"]["known_solution_grammar"]:
        raise FunSearchError("the free-search arm declared a grammar, so it is not a control")
    live_block = by_label["blinded_response_law"]
    if live_block["loop"] != free["loop"]:
        raise FunSearchError("the two search arms did not run the same loop configuration")
    if live_block["example_sampling"]["known_reproductions_in_the_population"] != free[
        "example_sampling"
    ]["known_reproductions_in_the_population"]:
        raise FunSearchError("the two search arms did not start from the same population")


