def vocabulary_violations(text: str, forbidden: Sequence[str]) -> list[str]:
    """Forbidden tokens present in ``text``, tokenised on letter runs only.

    The idiom is lifted from the blind planetary campaign: tokenising on letter runs means
    ``a_0``, ``MOND-like`` and ``dark_matter`` all decompose into the words being screened, so
    a leak cannot hide behind punctuation.
    """

    tokens = set(re.findall(r"[a-z]+", text.lower()))
    return sorted(tokens & {item.lower() for item in forbidden})


def guard_prompt(text: str, forbidden: Sequence[str]) -> str:
    """Return ``text`` unchanged, or refuse.  The refusal is the point of the guard."""

    violations = vocabulary_violations(text, forbidden)
    if violations:
        raise FunSearchError(f"prompt leaked forbidden vocabulary: {', '.join(violations)}")
    return text


