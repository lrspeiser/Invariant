def write_receipt(result: Mapping[str, Any], output: str | Path) -> None:
    path = Path(output)
    encoded = canonical_json_bytes(result) + b"\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(encoded)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="FunSearch-style proposal loop with anti-recall novelty pressure."
    )
    parser.add_argument("--output", default="runs/math/funsearch/loop-v1.json")
    parser.add_argument("--ledger", default="runs/math/funsearch/spend-ledger.json")
    parser.add_argument("--generations", type=int, default=LoopConfig().generations)
    parser.add_argument("--islands", type=int, default=LoopConfig().islands)
    parser.add_argument("--seed", type=int, default=LoopConfig().seed)
    parser.add_argument("--max-calls", type=int, default=800)
    parser.add_argument("--max-dollars-hundredths", type=int, default=1000)
    parser.add_argument("--proposer", choices=("auto", "mock", "claude"), default="auto")
    parser.add_argument("--claude", default="claude")
    parser.add_argument("--database", default="runs/math/prior-art/cf-corpus-v1.sqlite")
    parser.add_argument("--manifest", default="runs/math/prior-art/cf-corpus-v1-manifest.json")
    parser.add_argument("--no-corpus-problem", action="store_true")
    parser.add_argument("--validate-checked", action="store_true")
    parser.add_argument("--replay-checked", action="store_true")
    parser.add_argument("--hostile-suite", action="store_true")
    args = parser.parse_args(argv)

    if args.validate_checked:
        validate_receipt(json.loads(Path(args.output).read_text(encoding="utf-8")))
        print(json.dumps({"validated": True, "output": args.output}))
        return 0
    if args.replay_checked:
        report = replay_from_receipt(json.loads(Path(args.output).read_text(encoding="utf-8")))
        print(json.dumps(report, indent=2))
        return 0 if report["identical"] else 1
    if args.hostile_suite:
        print(json.dumps(run_hostile_suite(), indent=2))
        return 0

    result = run_loop(
        config=LoopConfig(
            islands=args.islands, generations=args.generations, seed=args.seed
        ),
        ledger_path=args.ledger,
        max_calls=args.max_calls,
        max_dollars_hundredths=args.max_dollars_hundredths,
        proposer_kind=args.proposer,
        claude_executable=args.claude,
        corpus_database=args.database,
        corpus_manifest=args.manifest,
        include_corpus_problem=not args.no_corpus_problem,
    )
    validate_receipt(result)
    write_receipt(result, args.output)
    print(
        json.dumps(
            {
                "proposer_used": result["proposer"]["used"],
                "live_model_attempt": result["proposer"]["live_model_attempt"],
                "hostile_programs_contained": result["sandbox"][
                    "all_hostile_programs_contained"
                ],
                "budget": {
                    "calls": result["budget"]["calls"],
                    "halt_reason": result["budget"]["halt_reason"],
                },
                "headline": result["headline"],
                "output": args.output,
                "content_sha256": result["content_sha256"],
            },
            indent=2,
        )
    )
    return 0


