def _runner_path() -> Path:
    """The runner source, materialised once per interpreter into a private temp file."""

    global _RUNNER_CACHE
    if _RUNNER_CACHE is None or not _RUNNER_CACHE.is_file():
        directory = Path(tempfile.mkdtemp(prefix="funsearch-runner-"))
        path = directory / "sandbox_runner.py"
        path.write_text(SANDBOX_RUNNER_SOURCE, encoding="utf-8")
        _RUNNER_CACHE = path
    return _RUNNER_CACHE


_RUNNER_CACHE: Path | None = None


def run_in_sandbox(
    source: str,
    entry: str,
    inputs: Sequence[Sequence[float]],
    budget: SandboxBudget,
    *,
    output_width: int = 1,
) -> SandboxOutcome:
    """Execute one untrusted program and return its outputs or a typed failure.

    Five independent layers stand between the program and the machine: the static screen, the
    restricted builtins table, the guarded ``__import__``, an isolated subprocess started with
    ``-I -S`` so no site packages are reachable, and a parent-side hard timeout backed by the
    child's own memory guard.  Nothing the program does reaches this function as an exception.
    """

    denials = static_screen(source, budget.import_allowlist)
    if denials:
        reason = "syntax_error" if denials[0].startswith("syntax_error") else "static_screen_denied"
        return SandboxOutcome(False, reason=reason, detail=";".join(denials)[:400])
    payload = {
        "source": source,
        "entry": entry,
        "inputs": [list(row) for row in inputs],
        "memory_bytes": int(budget.memory_bytes),
        "builtins_allowlist": list(BUILTIN_ALLOWLIST),
        "import_allowlist": list(budget.import_allowlist),
        "output_width": int(output_width),
    }
    started = time.perf_counter()
    with tempfile.TemporaryDirectory(prefix="funsearch-run-") as workspace:
        payload_path = Path(workspace) / "payload.json"
        result_path = Path(workspace) / "result.json"
        payload_path.write_text(json.dumps(payload), encoding="utf-8")
        command = [
            sys.executable,
            "-I",
            "-S",
            "-B",
            str(_runner_path()),
            str(payload_path),
            str(result_path),
        ]
        try:
            completed = subprocess.run(
                command,
                capture_output=True,
                timeout=float(budget.wall_seconds),
                check=False,
                cwd=workspace,
            )
        except subprocess.TimeoutExpired:
            return SandboxOutcome(
                False,
                reason="timeout",
                detail=f"wall_seconds={budget.wall_seconds}",
                elapsed_seconds=time.perf_counter() - started,
            )
        except OSError as error:
            return SandboxOutcome(
                False,
                reason="child_crashed",
                detail=str(error)[:200],
                elapsed_seconds=time.perf_counter() - started,
            )
        elapsed = time.perf_counter() - started
        if completed.returncode == MEMORY_EXIT_CODE:
            return SandboxOutcome(
                False,
                reason="memory_cap_exceeded",
                detail=f"memory_bytes={budget.memory_bytes}",
                elapsed_seconds=elapsed,
            )
        if not result_path.is_file():
            return SandboxOutcome(
                False,
                reason="child_crashed",
                detail=f"returncode={completed.returncode}",
                elapsed_seconds=elapsed,
            )
        try:
            parsed = json.loads(result_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
            return SandboxOutcome(
                False, reason="output_unparseable", detail=str(error)[:200], elapsed_seconds=elapsed
            )
    if not isinstance(parsed, Mapping) or "ok" not in parsed:
        return SandboxOutcome(False, reason="output_unparseable", detail="", elapsed_seconds=elapsed)
    if not parsed["ok"]:
        reason = str(parsed.get("reason", "child_crashed"))
        if reason not in SANDBOX_FAILURE_REASONS:
            reason = "child_crashed"
        return SandboxOutcome(
            False, reason=reason, detail=str(parsed.get("detail", ""))[:400], elapsed_seconds=elapsed
        )
    outputs = parsed.get("outputs")
    if not isinstance(outputs, list) or any(not isinstance(item, str) for item in outputs):
        return SandboxOutcome(False, reason="output_unparseable", detail="", elapsed_seconds=elapsed)
    return SandboxOutcome(True, tuple(outputs), elapsed_seconds=elapsed)


