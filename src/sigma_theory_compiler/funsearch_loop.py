@dataclass(frozen=True, slots=True)
class ScoredProgram:
    program_sha256: str
    source: str
    origin: str
    generation: int
    island: int
    sandbox: SandboxOutcome
    outputs: tuple[str, ...]
    quality: float
    quality_detail: dict[str, Any]
    novelty: NoveltyVerdict
    final_score: float

    def to_dict(self) -> dict[str, Any]:
        return {
            "program_sha256": self.program_sha256,
            "source": self.source,
            "origin": self.origin,
            "generation": self.generation,
            "island": self.island,
            "sandbox": self.sandbox.classification(),
            "outputs": list(self.outputs),
            "quality": format(self.quality, ".9f"),
            "quality_detail": self.quality_detail,
            "novelty": self.novelty.to_dict(),
            "final_score": format(self.final_score, ".9f"),
        }


def score_program(
    problem: ProblemSpec,
    source: str,
    *,
    origin: str = "proposed",
    generation: int = 0,
    island: int = 0,
    corpus: Any = None,
) -> ScoredProgram:
    """Execute, measure quality, measure novelty, and multiply.  Never raises on the program."""

    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    outcome = run_in_sandbox(
        source,
        problem.entry,
        problem.sandbox_inputs(),
        problem.sandbox,
        output_width=problem.output_width,
    )
    if not outcome.ok:
        return ScoredProgram(
            digest,
            source,
            origin,
            generation,
            island,
            outcome,
            (),
            0.0,
            {"reason": outcome.reason},
            NoveltyVerdict(0.0, "not_executable", {"sandbox_reason": outcome.reason}),
            0.0,
        )
    measured = EVALUATORS[problem.evaluator_id](problem, outcome.outputs)
    quality = float(measured["quality"])
    verdict = novelty_of(problem, outcome.outputs, corpus)
    return ScoredProgram(
        digest,
        source,
        origin,
        generation,
        island,
        outcome,
        outcome.outputs,
        quality,
        measured["detail"],
        verdict,
        quality * verdict.multiplier,
    )


