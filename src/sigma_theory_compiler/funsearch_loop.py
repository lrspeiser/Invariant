LEDGER_SCHEMA = "invariant-llm-spend-ledger-1.0"


def read_ledger(path: str | Path) -> int:
    """Integer hundredths of a dollar spent, in the watchdog's declared ledger format."""

    file = Path(path)
    if not file.is_file():
        return 0
    value = json.loads(file.read_text(encoding="utf-8"))
    if (
        not isinstance(value, Mapping)
        or set(value) != {"schema_version", "spent_dollars_hundredths"}
        or value["schema_version"] != LEDGER_SCHEMA
    ):
        raise FunSearchError("declared LLM ledger has the wrong shape or schema")
    spent = value["spent_dollars_hundredths"]
    if not isinstance(spent, int) or isinstance(spent, bool) or spent < 0:
        raise FunSearchError("ledger spent_dollars_hundredths must be a nonnegative int")
    return spent


def write_ledger(path: str | Path, spent_hundredths: int) -> None:
    file = Path(path)
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text(
        json.dumps(
            {"schema_version": LEDGER_SCHEMA, "spent_dollars_hundredths": int(spent_hundredths)},
            sort_keys=True,
        ),
        encoding="utf-8",
    )


@dataclass
class SpendGovernor:
    """Every proposal call is charged here first.  The loop halts cleanly when a cap binds."""

    ledger_path: Path
    max_calls: int
    max_dollars_hundredths: int
    charge_per_call_hundredths: int
    calls: int = 0
    charged_hundredths: int = 0
    opening_hundredths: int = 0
    halt_reason: str = ""

    def __post_init__(self) -> None:
        if self.max_calls < 1 or self.max_dollars_hundredths < 0:
            raise FunSearchError("spend governor caps must be positive")
        self.opening_hundredths = read_ledger(self.ledger_path)

    def may_call(self) -> bool:
        if self.calls >= self.max_calls:
            self.halt_reason = "call_cap_reached"
            return False
        projected = self.charged_hundredths + self.charge_per_call_hundredths
        if projected > self.max_dollars_hundredths:
            self.halt_reason = "dollar_cap_reached"
            return False
        return True

    def charge(self) -> None:
        self.calls += 1
        self.charged_hundredths += self.charge_per_call_hundredths
        write_ledger(self.ledger_path, self.opening_hundredths + self.charged_hundredths)

    def to_dict(self) -> dict[str, Any]:
        return {
            "ledger_path": str(self.ledger_path).replace("\\", "/"),
            "ledger_schema": LEDGER_SCHEMA,
            "max_calls": self.max_calls,
            "max_dollars_hundredths": self.max_dollars_hundredths,
            "charge_per_call_hundredths": self.charge_per_call_hundredths,
            "calls": self.calls,
            "charged_dollars_hundredths": self.charged_hundredths,
            "opening_ledger_hundredths": self.opening_hundredths,
            "closing_ledger_hundredths": self.opening_hundredths + self.charged_hundredths,
            "halt_reason": self.halt_reason,
        }


