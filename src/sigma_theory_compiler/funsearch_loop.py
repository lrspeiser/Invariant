@dataclass(frozen=True, slots=True)
class NoveltyVerdict:
    multiplier: float
    reason: str
    detail: dict[str, Any]

    def to_dict(self) -> dict[str, Any]:
        return {
            "novelty_multiplier": format(self.multiplier, ".9f"),
            "reason": self.reason,
            "detail": self.detail,
        }


def grammar_novelty(
    problem: ProblemSpec, outputs: Sequence[str]
) -> NoveltyVerdict:
    """Channel 1: behavioural distance to the nearest declared known family."""

    if not problem.known_solution_grammar:
        return NoveltyVerdict(
            1.0,
            "no_known_solution_grammar_declared",
            {
                "note": (
                    "the problem declares no known families, so no reproduction can be "
                    "detected on this channel and the multiplier is 1 by declaration"
                )
            },
        )
    observed = [float(item) for item in outputs]
    ranked: list[dict[str, Any]] = []
    for family in problem.known_solution_grammar:
        parameter, distance = fit_family(
            family, problem.probe_points, observed, problem.novelty_policy
        )
        ranked.append(
            {
                "family_id": family.family_id,
                "expression_text": family.expression_text,
                "best_fit_parameter": format(parameter, ".9g"),
                "distance": format(distance, ".6g"),
            }
        )
    ranked.sort(key=lambda item: (float(item["distance"]), item["family_id"]))
    nearest = ranked[0]
    distance = float(nearest["distance"])
    multiplier = problem.novelty_policy.multiplier_from_distance(distance)
    if multiplier == 0.0:
        reason = f"known_solution_grammar_match:{nearest['family_id']}"
    else:
        reason = f"distance_from_known_solution_grammar:{nearest['family_id']}"
    return NoveltyVerdict(
        multiplier,
        reason,
        {
            "nearest_family": nearest,
            "all_families": ranked,
            "zero_threshold": format(problem.novelty_policy.zero_threshold, ".6g"),
            "saturation_distance": format(problem.novelty_policy.saturation_distance, ".6g"),
        },
    )


def corpus_novelty(
    problem: ProblemSpec, outputs: Sequence[str], corpus: Any
) -> NoveltyVerdict:
    """Channel 2: the existing prior-art screen, including its equivalence-orbit test."""

    coefficients = _coefficients_from_outputs(outputs)
    if coefficients is None:
        return NoveltyVerdict(
            0.0,
            "induced_object_outside_declared_class",
            {"note": "the program did not emit a screenable coefficient pair"},
        )
    if corpus is None:
        return NoveltyVerdict(
            1.0,
            "corpus_unavailable",
            {"note": "no prior-art corpus was bound to this run"},
        )
    report = screen_induced_continued_fraction(coefficients, corpus)
    verdict = report["verdict"]
    if verdict == "KNOWN":
        return NoveltyVerdict(
            0.0,
            f"corpus_known:{report['test_that_fired']}",
            {
                "matched_record_id": report["matched_record_id"],
                "citation": report["citation"],
                "transformation_chain": report["transformation_chain"],
                "note": (
                    "the corpus screen exhibited and re-verified a transformation chain "
                    "carrying this continued fraction onto a cited record"
                ),
            },
        )
    if verdict == "INCONCLUSIVE_VALUE_MATCH":
        cap = problem.novelty_policy.inconclusive_value_match_cap
        return NoveltyVerdict(
            cap,
            "corpus_inconclusive_value_match",
            {
                "note": (
                    "a corpus record converges to the same limit but no declared "
                    "transformation chain connects the two; the multiplier is capped at the "
                    "declared inconclusive value rather than zeroed or trusted"
                ),
                "cap": format(cap, ".6g"),
            },
        )
    return NoveltyVerdict(
        1.0,
        "corpus_absent",
        {
            "note": (
                "absent from a finite corpus and outside its declared transformation "
                "orbits; this is a search pressure, not a novelty claim"
            )
        },
    )


def screen_induced_continued_fraction(
    coefficients: tuple[tuple[int, ...], ...], corpus: Any
) -> dict[str, Any]:
    """Adapt an induced ``(a_n, b_n)`` pair onto :func:`cf_prior_art_screen.screen_candidate`."""

    import mpmath as mp

    from .cf_prior_art_corpus import CFPattern, Poly, mobius_of, seq_from_poly
    from .cf_prior_art_screen import screen_candidate

    alpha, beta = coefficients
    pattern = CFPattern(seq_from_poly(Poly.of(*alpha)), seq_from_poly(Poly.of(*beta)))
    with mp.workdps(110):
        value = pattern.evaluate(220)
        if not mp.isfinite(value):
            return {
                "verdict": "NOT_FOUND_IN_CORPUS",
                "test_that_fired": "no_test_fired",
                "matched_record_id": None,
                "citation": None,
                "transformation_chain": [],
            }
        cf_value = mp.nstr(value, 100, strip_zeros=False)
    from .cf_prior_art_screen import Candidate

    candidate = Candidate(
        candidate_id="induced",
        target="e",
        pattern=pattern,
        wrap=mobius_of(1, 0, 0, 1),
        cf_value=cf_value,
        formula_text=f"a={alpha} b={beta}",
        source_label="funsearch_induced",
    )
    report = screen_candidate(corpus, candidate)
    matched = report.get("matched_record") or {}
    return {
        "verdict": report["verdict"],
        "test_that_fired": report["test_that_fired"],
        "matched_record_id": matched.get("record_id"),
        "citation": matched.get("citation"),
        "transformation_chain": report.get("transformation_chain", []),
    }


def novelty_of(problem: ProblemSpec, outputs: Sequence[str], corpus: Any = None) -> NoveltyVerdict:
    """The multiplier for one candidate, on the channel the problem declares."""

    if problem.novelty_channel == "prior_art_corpus":
        return corpus_novelty(problem, outputs, corpus)
    return grammar_novelty(problem, outputs)


