@dataclass(frozen=True, slots=True)
class KnownFamily:
    """One known solution, with its free parameters, declared for behavioural matching.

    ``expression_text`` is the hand-checkable statement of the family; ``evaluate`` is the
    same thing as code.  The two are pinned together by a test, because a grammar whose text
    and code disagree would quietly stop catching the thing it names.
    """

    family_id: str
    expression_text: str
    evaluate: Callable[[float, float], float]
    log10_parameter_bracket: tuple[float, float] = (-13.0, -8.0)

    def to_dict(self) -> dict[str, Any]:
        return {
            "family_id": self.family_id,
            "expression_text": self.expression_text,
            "log10_parameter_bracket": [
                format(item, ".6g") for item in self.log10_parameter_bracket
            ],
        }


def _mond_simple_nu(parameter: float, point: float) -> float:
    """y = u/2 * (1 + sqrt(1 + 4a/u)) -- the simple interpolating function's solved branch."""

    return 0.5 * point * (1.0 + math.sqrt(1.0 + 4.0 * parameter / point))


def _mond_deep(parameter: float, point: float) -> float:
    """y = sqrt(u a) -- the deep-regime limit."""

    return math.sqrt(point * parameter)


def _mond_standard_mu(parameter: float, point: float) -> float:
    """y = sqrt((u^2 + sqrt(u^4 + 4 u^2 a^2)) / 2) -- the standard mu(x)=x/sqrt(1+x^2) branch."""

    squared = point * point
    return math.sqrt(0.5 * (squared + math.sqrt(squared * squared + 4.0 * squared * parameter**2)))


def _aqual_nu_form(parameter: float, point: float) -> float:
    """y = u * nu(u/a) with nu(z) = (1 + sqrt(1 + 4/z))/2 -- the AQUAL algebraic rewrite."""

    ratio = point / parameter
    return point * 0.5 * (1.0 + math.sqrt(1.0 + 4.0 / ratio))


#: The declared known-solution grammar for the response-law problem: the MOND/AQUAL family
#: and its standard algebraic rewrites.  A candidate that lands on any of these -- however it
#: is written -- is a reproduction, and the loop must score it zero.
MOND_AQUAL_GRAMMAR: tuple[KnownFamily, ...] = (
    KnownFamily(
        "aqual_nu_form",
        "y = u * nu(u/a), nu(z) = (1 + sqrt(1 + 4/z))/2",
        _aqual_nu_form,
    ),
    KnownFamily(
        "mond_deep_limit",
        "y = sqrt(u * a)",
        _mond_deep,
    ),
    KnownFamily(
        "mond_simple_nu",
        "y = (u/2) * (1 + sqrt(1 + 4a/u))",
        _mond_simple_nu,
    ),
    KnownFamily(
        "mond_standard_mu",
        "y = sqrt((u^2 + sqrt(u^4 + 4 u^2 a^2)) / 2)",
        _mond_standard_mu,
    ),
)


#: The declared behavioural metrics.  ``log_relative_rms`` is the one to reach for whenever
#: the probe points span decades: a plain relative RMS is dominated by the largest scale, so
#: a program can be wrong by an order of magnitude at the small end and still look excellent.
DISTANCE_METRICS = ("log_relative_rms", "relative_rms")


def relative_rms_distance(candidate: Sequence[float], model: Sequence[float]) -> float:
    """``rms(candidate - model) / rms(candidate)``."""

    if len(candidate) != len(model) or not candidate:
        return math.inf
    numerator = 0.0
    denominator = 0.0
    for left, right in zip(candidate, model, strict=True):
        if not (math.isfinite(left) and math.isfinite(right)):
            return math.inf
        numerator += (left - right) ** 2
        denominator += left * left
    numerator = math.sqrt(numerator / len(candidate))
    denominator = math.sqrt(denominator / len(candidate))
    if denominator == 0.0:
        return numerator
    return numerator / denominator


def log_relative_rms_distance(candidate: Sequence[float], model: Sequence[float]) -> float:
    """``sqrt(mean(ln(candidate_i / model_i)^2))`` -- scale-free, so every decade counts once.

    For small deviations ``ln(c/m) ~ (c - m)/m``, so the number reads as a typical relative
    deviation and the declared thresholds keep their plain meaning.  A non-positive value is
    outside the metric's domain and returns infinity rather than being silently dropped.
    """

    if len(candidate) != len(model) or not candidate:
        return math.inf
    total = 0.0
    for left, right in zip(candidate, model, strict=True):
        if not (math.isfinite(left) and math.isfinite(right)) or left <= 0.0 or right <= 0.0:
            return math.inf
        total += math.log(left / right) ** 2
    return math.sqrt(total / len(candidate))


def distance_between(metric: str, candidate: Sequence[float], model: Sequence[float]) -> float:
    if metric == "log_relative_rms":
        return log_relative_rms_distance(candidate, model)
    if metric == "relative_rms":
        return relative_rms_distance(candidate, model)
    raise FunSearchError(f"undeclared distance metric: {metric}")


@dataclass(frozen=True, slots=True)
class NoveltyPolicy:
    """The declared, hand-checkable rule turning behaviour into a multiplier.

    ``distance`` is the deviation between the candidate's sealed outputs and the best-fit
    member of the nearest declared family, measured by the declared metric.  Every quantity
    in that formula is in the receipt -- the candidate's outputs, the family's expression and
    its fitted parameter -- so the multiplier can be recomputed by hand from the sealed record.
    """

    zero_threshold: float = 1e-6
    saturation_distance: float = 0.25
    inconclusive_value_match_cap: float = 0.25
    grid_points: int = 61
    refine_steps: int = 60
    metric: str = "log_relative_rms"

    def __post_init__(self) -> None:
        if self.metric not in DISTANCE_METRICS:
            raise FunSearchError(f"undeclared distance metric: {self.metric}")

    def distance(self, candidate: Sequence[float], model: Sequence[float]) -> float:
        return distance_between(self.metric, candidate, model)

    def multiplier_from_distance(self, distance: float) -> float:
        if distance <= self.zero_threshold:
            return 0.0
        span = self.saturation_distance - self.zero_threshold
        if span <= 0.0:
            return 1.0
        return min(1.0, (distance - self.zero_threshold) / span)

    def to_dict(self) -> dict[str, Any]:
        return {
            "zero_threshold": format(self.zero_threshold, ".6g"),
            "saturation_distance": format(self.saturation_distance, ".6g"),
            "inconclusive_value_match_cap": format(self.inconclusive_value_match_cap, ".6g"),
            "grid_points": self.grid_points,
            "refine_steps": self.refine_steps,
            "distance_metric": self.metric,
            "distance_metric_formula": (
                "sqrt(mean(ln(candidate_i / family_i)^2))"
                if self.metric == "log_relative_rms"
                else "rms(candidate - family) / rms(candidate)"
            ),
            "multiplier_rule": (
                "0 when distance <= zero_threshold; else "
                "min(1, (distance - zero_threshold) / (saturation_distance - zero_threshold))"
            ),
        }


def fit_family(
    family: KnownFamily,
    points: Sequence[float],
    observed: Sequence[float],
    policy: NoveltyPolicy,
) -> tuple[float, float]:
    """Best-fit the family's single parameter to ``observed``.  Returns ``(parameter, d)``.

    A declared log-spaced grid followed by a fixed number of golden-section refinements, so
    the fit is deterministic and reproducible without an optimiser library.
    """

    def deviation(log_parameter: float) -> float:
        parameter = 10.0**log_parameter
        model: list[float] = []
        for point in points:
            try:
                value = family.evaluate(parameter, point)
            except (ValueError, ZeroDivisionError, OverflowError):
                return math.inf
            if not math.isfinite(value):
                return math.inf
            model.append(value)
        return policy.distance(observed, model)

    low, high = family.log10_parameter_bracket
    grid = [
        low + (high - low) * index / (policy.grid_points - 1) for index in range(policy.grid_points)
    ]
    scores = [deviation(item) for item in grid]
    best_index = min(range(len(grid)), key=lambda index: (scores[index], index))
    left = grid[max(0, best_index - 1)]
    right = grid[min(len(grid) - 1, best_index + 1)]
    best_log, best_value = grid[best_index], scores[best_index]
    ratio = (math.sqrt(5.0) - 1.0) / 2.0
    probe_left = right - ratio * (right - left)
    probe_right = left + ratio * (right - left)
    value_left, value_right = deviation(probe_left), deviation(probe_right)
    for _ in range(policy.refine_steps):
        if value_left <= value_right:
            right, probe_right, value_right = probe_right, probe_left, value_left
            probe_left = right - ratio * (right - left)
            value_left = deviation(probe_left)
        else:
            left, probe_left, value_left = probe_left, probe_right, value_right
            probe_right = left + ratio * (right - left)
            value_right = deviation(probe_right)
    for log_parameter, value in ((probe_left, value_left), (probe_right, value_right)):
        if value < best_value:
            best_log, best_value = log_parameter, value
    return 10.0**best_log, best_value


