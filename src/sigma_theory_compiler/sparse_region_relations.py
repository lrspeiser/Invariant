"""Sparse-region relation discovery over self-generated constants (DG4).

Three prior campaigns enumerated 1.19e8 continued-fraction ordinals and 3.25e9
series/product/integral ordinals and found nothing new.  The cause is structural, not
effort, and this module is built against a written diagnosis of it:

*(i) the targets were the classical constants.*  ``pi``, ``e``, ``ln 2``, ``zeta(3)`` and
Catalan sit in the most heavily mined neighbourhoods in mathematics, so an enumeration aimed
at them can only rediscover.  **Fix:** the targets here are *generated by this module*.
Component 1 builds a pool of exactly-computable real constants -- rational-shift zeta sums,
their alternating and character twists, Epstein lattice sums, continued fractions the earlier
enumeration computed but never matched, and integrals off the Beta/zeta locus -- each carrying
its own generating definition.  The definition *is* the object's identity: every value in the
receipt is reproducible from its definition string and parameters alone.

*(ii) the proof step was circular.*  Pincherle, Euler-Minding, Gauss ``2F1`` and Beta
reduction *are* the classical families, so anything provable by that toolkit is thereby
classical, and the toolkit was being used as an admission gate.  **Fix:** the same toolkit is
run here as a *classifier*, and failure to reduce is recorded as a positive signal rather than
a blocker.  A relation the classical reduction ladder cannot touch is labelled
``SURVIVES_CLASSICAL_REDUCTION`` and reported in full with the exact techniques that were
tried and failed.

*(iii) the grammar was a curated list of families named because they were fruitful.*
**Fix:** Component 2 measures, per declared region, how mined that region is -- corpus hits
and the fraction of the region's members that reduce to a classical closed form under a
bounded PSLQ search -- and Component 3 hunts only where that measurement says the literature
is thin.  The density map is a deliverable in its own right: it is the first quantitative
answer this project has to "where has nobody looked".

**What ``SURVIVES_CLASSICAL_REDUCTION`` does and does not mean.**  It means: true to 400
decimal digits with independently recomputed constants, and untouched by the six declared
classical reduction techniques.  It does *not* mean new.  The claim
``unreduced_is_not_novel_it_is_unreviewed`` is sealed into every receipt precisely because the
honest reading of an unreduced survivor is "nobody on this machine has reviewed it", and
``corpus_absence_establishes_novelty`` stays ``false``.  Everything here needs a human.

Numerics, all exact-convergent with declared error control:

* **Sum classes.**  For ``P(n) = n^p + a n + b`` squarefree with no root at a positive
  integer, and a period-``M`` weight ``w`` with either ``sum_t w(t) = 0`` or ``deg P >= 2``,
  partial fractions over the roots give the closed form
  ``S = -(1/M) sum_{t,j} w(t) psi((t - r_j)/M) / P'(r_j)``.  It is exact, it costs a handful
  of digamma evaluations, and it is cross-checked against a structurally independent
  Hurwitz-zeta tail expansion on a declared sample.
* **Epstein class.**  The Ewald/incomplete-gamma split of the Epstein zeta function
  ``Z_Q(s) = pi^s/Gamma(s) [ sum_{v!=0} Gamma(s, pi Q(v)) (pi Q(v))^-s
  + Lambda^-1/2 ( sum_{v!=0} E_s(pi Q*(v)) + 1/(s-1) ) - 1/s ]`` converts an ``N^(2-2s)``
  lattice sum into two Gaussian-decaying ones.  The truncation radius is solved from the
  requested precision and re-measured at a larger radius.
* **Continued-fraction class.**  Depth-``D`` and depth-``2D`` convergents must agree; a member
  that will not converge is dropped, never estimated.
* **Integral class.**  ``inverse_symbolic_families.integral_value_mp`` -- tanh-sinh in the log
  domain with the abscissa range solved from the precision.

Every class certifies its own error bound by dual-precision agreement, and **a member whose
bound cannot be certified is dropped, not estimated**.

One candidate class was considered and deliberately left out.  Infinite products from family
``P`` are enumerable and uncatalogued in the same sense as the continued fractions, but the
grammar's convergence condition (equal degree, equal leading and equal subleading coefficient)
is exactly the condition under which the product *has* the closed form
``prod_j Gamma(k0 - beta_j) / prod_i Gamma(k0 - alpha_i)``.  Every convergent member is
therefore classical by construction, the class could contain no sparse region, and adding it
would have inflated the pool without adding anywhere to look.

Controls are run-aborting: a planted telescoping relation must be found and must come back
``KNOWN``; a random-coefficient false relation must not be found at the declared bound; a
relation constructed to hold at 200 digits and fail at 400 must be caught and discarded; and
the 400-digit re-verification path must be proven independent of the cached pool values.
"""

