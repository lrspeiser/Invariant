def polynomial_is_squarefree(p: int, a: int, b: int) -> bool:
    """``n^p + a n + b`` has no repeated root (exact, over the rationals)."""

    n = sp.Symbol("n")
    poly = sp.Poly(n**p + a * n + b, n)
    return sp.degree(sp.gcd(poly, poly.diff(n)), n) == 0


def polynomial_positive_integer_roots(p: int, a: int, b: int) -> list[int]:
    """Every integer ``n >= 1`` with ``n^p + a n + b = 0``.

    For ``n >= 1 + |a| + |b|`` we have ``n^p >= n^2 >= n(1 + |a| + |b|) > |a| n + |b|``, so the
    search above that bound is provably empty and the check below is exhaustive.
    """

    limit = 1 + abs(a) + abs(b)
    return [n for n in range(1, limit + 1) if n**p + a * n + b == 0]


def polynomial_rational_roots(p: int, a: int, b: int) -> list[Fraction] | None:
    """All roots as rationals, or ``None`` when at least one root is irrational."""

    n = sp.Symbol("n")
    factored = sp.factor_list(sp.Poly(n**p + a * n + b, n).as_expr())
    roots: list[Fraction] = []
    for factor, multiplicity in factored[1]:
        poly = sp.Poly(factor, n)
        if poly.degree() != 1:
            return None
        c1, c0 = poly.all_coeffs()
        value = Fraction(int(-c0), int(c1))
        roots.extend([value] * multiplicity)
    return sorted(roots)


def sum_class_value(
    p: int, a: int, b: int, weights: Sequence[int], modulus: int, dps: int
) -> tuple[mp.mpf, mp.mpf]:
    """Exact sum-class value and the magnitude of its (must-vanish) imaginary part.

    ``S = -(1/M) sum_{t=1..M} sum_j w(t) psi((t - r_j)/M) / P'(r_j)``.  The imaginary part is
    zero in exact arithmetic because non-real roots occur in conjugate pairs with conjugate
    residues; its measured magnitude is returned as part of the numerical certificate.
    """

    with mp.workdps(dps):
        total = mp.mpc(0)
        for root, residue in _roots_and_residues(p, a, b, dps):
            for index, weight in enumerate(weights, start=1):
                if weight == 0:
                    continue
                total += weight * residue * mp.digamma((index - root) / modulus)
        total = -total / modulus
        return +mp.mpf(total.real), +mp.mpf(abs(total.imag))


@lru_cache(maxsize=8192)
def _roots_and_residues(p: int, a: int, b: int, dps: int) -> tuple[tuple[mp.mpc, mp.mpc], ...]:
    """Roots of ``n^p + a n + b`` with residues ``1/P'(r)`` at working precision ``dps``.

    Cached because the same polynomial carries all four twists of the sum classes, so the root
    solve is amortised four ways.  ``extraprec`` is three times the decimal precision in bits,
    which is ample for a squarefree integer polynomial of degree at most four with coefficients
    in the declared box -- and any shortfall is caught by the dual-precision certificate, which
    drops the member rather than estimating it.
    """

    with mp.workdps(dps):
        coefficients = [mp.mpf(1)] + [mp.mpf(0)] * p
        coefficients[p - 1] = mp.mpf(a)
        coefficients[p] = mp.mpf(b)
        roots = mp.polyroots(coefficients, maxsteps=500, extraprec=3 * dps)
        return tuple((root, 1 / (p * root ** (p - 1) + a)) for root in roots)


def sum_class_crosscheck(
    p: int, a: int, b: int, weights: Sequence[int], modulus: int, dps: int = 40
) -> mp.mpf:
    """Structurally independent value: head terms plus a Hurwitz-zeta tail expansion.

    Nothing here touches digamma or the partial-fraction decomposition.  For ``n >= N`` the
    summand is expanded as ``n^-p sum_k (-1)^k (a n^(1-p) + b n^-p)^k`` and each power of ``n``
    is summed by ``zeta(e, N)`` restricted to the residue class, so the cross-check exercises a
    different identity, a different mpmath primitive and a different truncation argument.
    """

    with mp.workdps(dps + 25):
        head = 2 * (abs(a) + abs(b) + 2) + modulus * 12
        head += modulus - (head % modulus)
        total = mp.mpf(0)
        for n in range(1, head):
            weight = weights[(n - 1) % modulus]
            if weight:
                total += mp.mpf(weight) / (mp.mpf(n) ** p + a * n + b)
        limit = mp.mpf(10) ** (-(dps + 12))
        for k in range(400):
            layer = mp.mpf(0)
            magnitude = mp.mpf(0)
            for i in range(k + 1):
                j = k - i
                coefficient = mp.binomial(k, i) * mp.mpf(a) ** i * mp.mpf(b) ** j
                if coefficient == 0:
                    continue
                exponent = p + i * (p - 1) + j * p
                sign = mp.mpf(-1) ** k
                for residue in range(modulus):
                    weight = weights[(head + residue - 1) % modulus]
                    if weight == 0:
                        continue
                    shift = mp.mpf(head + residue) / modulus
                    tail = mp.zeta(exponent, shift) / mp.mpf(modulus) ** exponent
                    layer += sign * coefficient * weight * tail
                    magnitude += abs(coefficient * tail)
            total += layer
            if k > 2 and magnitude < limit:
                break
        return +mp.mpf(total)


