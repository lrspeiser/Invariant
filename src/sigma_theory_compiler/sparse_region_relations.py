def hunt_subset(
    subset: Mapping[str, Any], values: Mapping[str, mp.mpf]
) -> dict[str, Any] | None:
    """One bounded PSLQ call at 200 digits, or ``None`` when nothing is found."""

    names = list(subset["constants"])
    anchors = list(subset["anchors"])
    with mp.workdps(int(RELATION_HUNT["fit_dps"])):
        vector = [values[name] for name in names] + [
            classical_value(anchor) for anchor in anchors
        ]
        relation = mp.pslq(
            vector,
            tol=mp.mpf(str(RELATION_HUNT["tol"])),
            maxcoeff=int(RELATION_HUNT["max_coefficient"]),
            maxsteps=int(RELATION_HUNT["max_steps"]),
        )
        if relation is None:
            return None
        coefficients = [int(item) for item in relation]
        if max(abs(item) for item in coefficients) > int(RELATION_HUNT["max_coefficient"]):
            return None
        support = sum(1 for item in coefficients[: len(names)] if item)
        if support < int(RELATION_HUNT["minimum_pool_support"]):
            return None
        residual = mp.mpf(0)
        norm = mp.mpf(0)
        for coefficient, item in zip(coefficients, vector, strict=True):
            residual += coefficient * item
            norm += abs(coefficient * item)
        normalized = abs(residual) / norm if norm else mp.mpf(1)
        if not normalized < mp.mpf(str(RELATION_HUNT["fit_normalized_residual_threshold"])):
            return None
        return {
            "schedule": subset["schedule"],
            "constants": names,
            "anchors": anchors,
            "coefficients": coefficients,
            "pool_support": support,
            "normalized_residual_at_200dps": (
                "0e0" if normalized == 0 else mp.nstr(normalized, 5)
            ),
        }


def verify_at_400(hit: Mapping[str, Any], records: Mapping[str, Mapping[str, Any]]) -> dict[str, Any]:
    """Re-verify a 200-digit hit at 400 digits with values recomputed from definitions.

    The recomputation reads only ``pool_class`` and ``parameters``.  It never reads the cached
    ``value`` field, which is the property the cache-corruption control demonstrates.
    """

    dps = int(RELATION_HUNT["verify_dps"])
    names = list(hit["constants"])
    anchors = list(hit["anchors"])
    with mp.workdps(dps + GUARD_LOW):
        values = [recompute_value(records[name], dps) for name in names]
        values += [classical_value(anchor) for anchor in anchors]
        residual = mp.mpf(0)
        norm = mp.mpf(0)
        for coefficient, item in zip(hit["coefficients"], values, strict=True):
            residual += coefficient * item
            norm += abs(coefficient * item)
        normalized = abs(residual) / norm if norm else mp.mpf(1)
        survived = bool(
            normalized < mp.mpf(str(RELATION_HUNT["verify_normalized_residual_threshold"]))
        )
        return {
            "verify_dps": dps,
            "values_recomputed_from_definitions": True,
            "normalized_residual_at_400dps": (
                "0e0" if normalized == 0 else mp.nstr(normalized, 5)
            ),
            "survived": survived,
            "discard_reason": None if survived else "PSLQ artifact: died at 400 digits",
        }


def render_relation(hit: Mapping[str, Any]) -> str:
    """The relation as plain text: ``c1*id1 + c2*id2 + ... = 0``."""

    terms: list[str] = []
    labels = list(hit["constants"]) + list(hit["anchors"])
    for coefficient, label in zip(hit["coefficients"], labels, strict=True):
        if coefficient == 0:
            continue
        body = str(abs(coefficient)) if label == "one" else (
            label if abs(coefficient) == 1 else f"{abs(coefficient)}*{label}"
        )
        sign = "+" if coefficient > 0 else "-"
        terms.append(f"{sign} {body}" if terms else (body if coefficient > 0 else f"-{body}"))
    return (" ".join(terms) if terms else "0") + " = 0"


