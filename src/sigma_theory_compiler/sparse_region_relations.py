def principal_form(discriminant: int) -> tuple[int, int, int]:
    """The principal binary quadratic form ``(A, B, C)`` of a negative discriminant.

    Every form in this pool has leading coefficient one, hence represents one, hence is
    ``SL(2, Z)``-equivalent to the principal form -- which is why the pool is indexed by
    discriminant rather than by ``(c, d)``: distinct ``(c, d)`` with the same discriminant
    give literally the same lattice sum.
    """

    if discriminant >= 0:
        raise SparseRegionError("Epstein pool needs a negative discriminant")
    if discriminant % 4 == 0:
        return (1, 0, -discriminant // 4)
    if discriminant % 4 == 1:
        return (1, 1, (1 - discriminant) // 4)
    raise SparseRegionError("a discriminant is 0 or 1 mod 4")


def class_number(discriminant: int) -> int:
    """``h(D)`` by counting reduced *primitive* positive-definite forms of discriminant ``D``.

    Reduced means ``|b| <= a <= c`` with ``b >= 0`` whenever ``|b| = a`` or ``a = c``.
    Primitive means ``gcd(a, b, c) = 1`` -- omitting it would count ``(2, 0, 2)`` at ``D = -16``
    and ``(2, 2, 2)`` at ``D = -12`` and report ``h = 2`` for two discriminants that are
    famously class number one.
    """

    if discriminant >= 0:
        raise SparseRegionError("class number here is for negative discriminants only")
    count = 0
    bound = math.isqrt(-discriminant // 3) + 1
    for b in range(-bound, bound + 1):
        if (b * b - discriminant) % 4:
            continue
        product = (b * b - discriminant) // 4
        for a in range(max(abs(b), 1), math.isqrt(product) + 1):
            if product % a:
                continue
            c = product // a
            if c < a or abs(b) > a:
                continue
            if (a == c or abs(b) == a) and b < 0:
                continue
            if math.gcd(math.gcd(a, abs(b)), c) != 1:
                continue
            count += 1
    return count


def kronecker_character(discriminant: int, n: int) -> int:
    """``chi_D(n)`` -- the Kronecker symbol ``(D|n)`` for ``D < 0`` and ``n >= 1``.

    The even part is peeled off by ``(D|2) = 0, 1, -1`` according to ``D mod 8``, and the odd
    part is the Jacobi symbol.  No factorisation, so this is safe inside a summation loop.
    """

    if n < 1:
        raise SparseRegionError("the character is evaluated at positive integers")
    odd = n
    twos = 0
    while odd % 2 == 0:
        odd //= 2
        twos += 1
    result = 1
    if twos:
        if discriminant % 2 == 0:
            return 0
        result = (1 if discriminant % 8 in (1, 7) else -1) ** twos
    if odd == 1:
        return result
    return result * int(sp.jacobi_symbol(discriminant % odd, odd))


def representation_counts(form: tuple[int, int, int], bound: int) -> dict[int, int]:
    """``{k: #{(m,n) != 0 : Q(m,n) = k}}`` for every ``k <= bound``, by exact integer bounds.

    ``Q(m,n) <= bound`` forces ``m^2 (-D) <= 4 C bound``, and for each admissible ``m`` the
    ``n`` range is the exact root interval of a quadratic with integer coefficients.  Nothing
    is scanned that cannot contribute, and the values are integers, so the transcendental work
    downstream is one call per *represented integer* rather than one call per lattice point.
    """

    a, b, c = form
    discriminant = b * b - 4 * a * c
    counts: dict[int, int] = {}
    m_limit = math.isqrt(4 * c * bound // (-discriminant)) + 1
    for m in range(-m_limit, m_limit + 1):
        inner = 4 * c * bound + discriminant * m * m
        if inner < 0:
            continue
        root = math.isqrt(inner)
        low = -(-(-b * m - root - 1) // (2 * c)) - 1
        high = (-b * m + root) // (2 * c) + 1
        for n in range(low, high + 1):
            if m == 0 and n == 0:
                continue
            value = a * m * m + b * m * n + c * n * n
            if 0 < value <= bound:
                counts[value] = counts.get(value, 0) + 1
    return counts


def epstein_value(discriminant: int, s: int, dps: int, radius_scale: float = 1.0) -> mp.mpf:
    """Epstein zeta of the principal form by the Ewald/incomplete-gamma split.

    The form is first normalised to determinant one, ``Qt = Q / sqrt(det)``, so
    ``Z_Q(s) = det^(-s/2) Z_Qt(s)``.  That is not cosmetic: at determinant one the inverse
    form ``Qt*`` satisfies ``Qt*(m, n) = Qt(n, -m)``, so the direct and dual Ewald sums run
    over the *same* point set and

    ``Gamma(s) pi^-s Z_Qt(s) = sum_{v!=0} [ Gamma(s, pi Qt(v)) (pi Qt(v))^-s + E_s(pi Qt(v)) ]
    + 1/(s-1) - 1/s``.

    ``Q(v)`` is a non-negative integer, so the sum is reorganised over *represented integers*
    with their multiplicities.  Both summands decay like ``exp(-pi Qt)``, so the truncation
    radius is linear in the requested digits; ``radius_scale`` enlarges it for the
    error-bound measurement.
    """

    form = principal_form(discriminant)
    with mp.workdps(dps + 25):
        det = mp.mpf(-discriminant) / 4
        scale = mp.sqrt(det)
        need = (mp.mpf(dps) + 20) * mp.log(10)
        radius = radius_scale * need / mp.pi
        bound = int(mp.floor(radius * scale)) + 1
        counts = representation_counts(form, bound)
        order = mp.mpf(s)
        factorial = mp.factorial(s - 1)
        total = mp.mpf(0)
        for value in sorted(counts):
            argument = mp.pi * value / scale
            if argument > need:
                continue
            decay = mp.e ** (-argument)
            upper = mp.mpf(0)
            term = mp.mpf(1)
            for j in range(s):
                upper += term / argument**order * argument**j
                term /= j + 1
            upper *= factorial * decay
            total += counts[value] * (upper + mp.expint(order, argument))
        total += 1 / (order - 1) - 1 / order
        return +mp.mpf(scale ** (-order) * mp.pi**order / mp.gamma(order) * total)


def epstein_factorisation_value(discriminant: int, s: int, dps: int) -> mp.mpf:
    """``w * zeta(s) * L(s, chi_D)`` -- the class-number-one closed form.

    ``w`` is the unit count of the order (6 at ``D = -3``, 4 at ``D = -4``, 2 otherwise).  The
    Dirichlet ``L`` value is assembled from Hurwitz zeta over the residue classes,
    ``L(s, chi) = |D|^-s sum_{r=1..|D|} chi(r) zeta(s, r/|D|)`` -- a different code path from
    :func:`epstein_value` in every respect, which is what makes it evidence.
    """

    units = {-3: 6, -4: 4}.get(discriminant, 2)
    modulus = -discriminant
    with mp.workdps(dps + 25):
        lvalue = mp.mpf(0)
        for residue in range(1, modulus + 1):
            character = kronecker_character(discriminant, residue)
            if character:
                lvalue += character * mp.zeta(s, mp.mpf(residue) / modulus)
        lvalue /= mp.mpf(modulus) ** s
        return +mp.mpf(units * mp.zeta(s) * lvalue)


