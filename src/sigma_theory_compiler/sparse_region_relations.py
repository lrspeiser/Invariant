def _digest_stream(seed: str) -> Iterator[int]:
    """Endless deterministic byte stream from iterated SHA-256 over ``seed``."""

    state = seed.encode("utf-8")
    while True:
        state = hashlib.sha256(state).digest()
        yield from state


def deterministic_integers(seed: str, count: int, modulus: int) -> list[int]:
    """``count`` integers in ``[0, modulus)`` from the declared SHA-256 stream."""

    if modulus <= 0:
        raise SparseRegionError("modulus must be positive")
    stream = _digest_stream(seed)
    out: list[int] = []
    while len(out) < count:
        value = 0
        for _ in range(8):
            value = (value << 8) | next(stream)
        out.append(value % modulus)
    return out


