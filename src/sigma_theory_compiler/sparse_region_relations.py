def planted_relation_control(records: Mapping[str, Mapping[str, Any]], context: Any) -> dict[str, Any]:
    """A relation that is exactly true by telescoping must be found and must come back KNOWN.

    ``sum 1/(n^2 + n) = sum 1/(n(n+1)) = 1`` and ``sum 1/(n^2 + 2n) = sum 1/(n(n+2)) = 3/4``
    both telescope, so ``3*S(1,0,2) - 4*S(2,0,2) = 0`` exactly.  The receipt records the
    coefficients PSLQ actually returns, not the ones we expected, and the control passes only
    if the returned relation survives 400 digits *and* the ladder reduces it.

    No classical anchor is offered.  With ``one`` in the vector PSLQ would return the shorter
    ``S(1,0,2) - 1 = 0`` instead, whose pool support is one and which the hunt therefore
    rejects -- a real property of a bounded single-relation search, and the reason the hunt's
    ``NOT FOUND`` verdicts are always relative to the declared subset *and* its anchors.
    """

    left = "zeta_shift:p2:a1:b0"
    right = "zeta_shift:p2:a2:b0"
    if left not in records or right not in records:
        return {"available": False, "control_passed": False, "reason": "planted members absent"}
    with mp.workdps(int(RELATION_HUNT["fit_dps"])):
        values = {name: mp.mpf(records[name]["value"]) for name in (left, right)}
    subset = {"schedule": "planted_control", "constants": [left, right], "anchors": []}
    hit = hunt_subset(subset, values)
    if hit is None:
        return {
            "available": True,
            "control_passed": False,
            "reason": "PSLQ did not find the planted telescoping relation",
        }
    verification = verify_at_400(hit, records)
    reduction = reduce_relation(hit, records, context)
    passed = bool(verification["survived"] and reduction["verdict"] == "KNOWN_BY_PROOF_FAMILY")
    return {
        "available": True,
        "definitions": {name: records[name]["definition"] for name in (left, right)},
        "relation": render_relation(hit),
        "coefficients": hit["coefficients"],
        "verification": verification,
        "reduction_verdict": reduction["verdict"],
        "technique_that_fired": reduction["technique_that_fired"],
        "control_passed": passed,
    }


def false_relation_control(
    records: Mapping[str, Mapping[str, Any]], preferred: Sequence[str] = ()
) -> dict[str, Any]:
    """A pseudorandom constant must not enter a relation with pool constants under the bound.

    The pass condition is that no relation is found *involving the decoy*.  Distinguishing that
    from "no relation at all" matters: the pool is allowed to contain relations among its own
    members -- finding those is the entire point of Component 3 -- and a genuine pool relation
    surfacing here would otherwise be misread as the negative control failing.
    """

    names = [name for name in preferred if name in records][:4]
    if len(names) < 4:
        names = sorted(records)[:4]
    if len(names) < 4:
        return {"control_passed": False, "reason": "pool too small for the control"}
    digits = engine._pseudorandom_decimal_digits(FALSE_RELATION_SEED, 260)
    with mp.workdps(int(RELATION_HUNT["fit_dps"])):
        decoy = mp.mpf("0." + digits)
        vector = [decoy] + [mp.mpf(records[name]["value"]) for name in names]
        vector.append(classical_value("one"))
        relation = mp.pslq(
            vector,
            tol=mp.mpf(str(RELATION_HUNT["tol"])),
            maxcoeff=int(RELATION_HUNT["max_coefficient"]),
            maxsteps=int(RELATION_HUNT["max_steps"]),
        )
    coefficients = None if relation is None else [int(item) for item in relation]
    decoy_used = bool(coefficients is not None and coefficients[0] != 0)
    return {
        "decoy_definition": (
            f"0.<260 digits from iterated sha256 of '{FALSE_RELATION_SEED}'>"
        ),
        "pool_constants": names,
        "max_coefficient": int(RELATION_HUNT["max_coefficient"]),
        "relation_found": relation is not None,
        "relation_involves_the_decoy": decoy_used,
        "coefficients": coefficients,
        "control_passed": not decoy_used,
        "note": (
            "absence is bounded: no relation with coefficients under the declared bound, never "
            "a proof that none exists"
        ),
    }


def precision_artifact_control(records: Mapping[str, Mapping[str, Any]]) -> dict[str, Any]:
    """A relation true at 200 digits by construction and false at 400 must be discarded."""

    names = sorted(records)[:2]
    if len(names) < 2:
        return {"control_passed": False, "reason": "pool too small for the control"}
    offset = mp.mpf(10) ** -260
    with mp.workdps(int(RELATION_HUNT["fit_dps"])):
        first = mp.mpf(records[names[0]]["value"])
        second = mp.mpf(records[names[1]]["value"])
        fake = first + 2 * second + offset
        vector = [fake, first, second]
        relation = mp.pslq(
            vector,
            tol=mp.mpf(str(RELATION_HUNT["tol"])),
            maxcoeff=int(RELATION_HUNT["max_coefficient"]),
            maxsteps=int(RELATION_HUNT["max_steps"]),
        )
    found = relation is not None
    survived = False
    residual = "not_evaluated"
    if found:
        with mp.workdps(int(RELATION_HUNT["verify_dps"]) + GUARD_LOW):
            fresh_first = recompute_value(records[names[0]], int(RELATION_HUNT["verify_dps"]))
            fresh_second = recompute_value(records[names[1]], int(RELATION_HUNT["verify_dps"]))
            fresh_fake = fresh_first + 2 * fresh_second + mp.mpf(10) ** -260
            values = [fresh_fake, fresh_first, fresh_second]
            total = mp.mpf(0)
            norm = mp.mpf(0)
            for coefficient, item in zip(relation, values, strict=True):
                total += int(coefficient) * item
                norm += abs(int(coefficient) * item)
            normalized = abs(total) / norm if norm else mp.mpf(1)
            residual = mp.nstr(normalized, 5)
            survived = bool(
                normalized
                < mp.mpf(str(RELATION_HUNT["verify_normalized_residual_threshold"]))
            )
    return {
        "construction": (
            f"x = {names[0]} + 2*{names[1]} + 1e-260, which satisfies "
            "x - a - 2b = 0 to 260 digits and fails it at 400"
        ),
        "found_at_200dps": found,
        "coefficients": None if relation is None else [int(item) for item in relation],
        "normalized_residual_at_400dps": residual,
        "survived_400dps": survived,
        "control_passed": bool(found and not survived),
    }


def independence_control(records: Mapping[str, Mapping[str, Any]]) -> dict[str, Any]:
    """Corrupt the cached value and show the verification path is unaffected."""

    name = min(records)
    record = records[name]
    dps = int(RELATION_HUNT["verify_dps"])
    with mp.workdps(dps + GUARD_LOW):
        clean = recompute_value(record, dps)
    corrupted = {**record, "value": "0.123456789"}
    with mp.workdps(dps + GUARD_LOW):
        after = recompute_value(corrupted, dps)
        identical = bool(clean == after)
        stored = mp.mpf(record["value"])
        agrees = bool(abs(clean - stored) / max(mp.mpf(1), abs(stored)) < mp.mpf("1e-190"))
    return {
        "constant_id": name,
        "cache_corrupted_to": "0.123456789",
        "recomputation_unchanged": identical,
        "recomputation_matches_uncorrupted_cache": agrees,
        "control_passed": bool(identical and agrees),
        "note": (
            "recompute_value reads pool_class and parameters only; the cached value field is "
            "never an input to the 400-digit verification"
        ),
    }


