def digamma_expansion(record: Mapping[str, Any], dps: int) -> list[tuple[mp.mpc, mp.mpc]]:
    """``[(coefficient, argument)]`` with ``S = sum coefficient * psi(argument)``.

    Gauss's multiplication theorem refines every sum-class member onto the *same* modulus-12
    grid: ``psi((t-r)/M) = ln(L/M) + (M/L) sum_k psi((t + kM - r)/L)``, and the logarithms
    drop out because ``(sum_t w)(sum_j 1/P'(r_j))`` is zero for every admissible member.  The
    upshot is that constants of different moduli become directly comparable.
    """

    parameters = record["parameters"]
    p = int(parameters["p"])
    a = int(parameters["a"])
    b = int(parameters["b"])
    modulus = int(parameters["modulus"])
    weights = [int(item) for item in parameters["weights"]]
    refined = DIGAMMA_REFINEMENT_MODULUS
    if refined % modulus:
        raise SparseRegionError("the refinement modulus must be a multiple of every class")
    terms: list[tuple[mp.mpc, mp.mpc]] = []
    with mp.workdps(dps):
        for root, residue in _roots_and_residues(p, a, b, dps):
            for m in range(1, refined + 1):
                weight = weights[(m - 1) % modulus]
                if weight == 0:
                    continue
                terms.append((-weight * residue / refined, (m - root) / refined))
    return terms


def canonicalise_digamma_terms(
    terms: Sequence[tuple[mp.mpc, mp.mpc]], dps: int
) -> tuple[list[tuple[mp.mpc, mp.mpc]], mp.mpc, list[tuple[mp.mpc, mp.mpc]]]:
    """Shift arguments into ``Re in [0,1)``, then reflect into ``Re <= 1/2``.

    Returns the canonical ``psi`` terms, the accumulated elementary scalar from
    ``psi(x+1) = psi(x) + 1/x``, and the ``pi cot`` terms picked up by reflection.
    """

    scalar = mp.mpc(0)
    cot_terms: list[tuple[mp.mpc, mp.mpc]] = []
    canonical: list[tuple[mp.mpc, mp.mpc]] = []
    with mp.workdps(dps):
        guard = mp.mpf(10) ** (-(dps // 3))

        def strip(coefficient: mp.mpc, argument: mp.mpc) -> tuple[mp.mpc, mp.mpc]:
            """``psi(argument) = psi(reduced) + residue/coefficient``, ``Re(reduced)`` in (0,1].

            The strip is (0, 1] and not [0, 1): ``psi`` has a pole at every non-positive
            integer, and stopping at 1 rather than stepping onto 0 is what keeps ``1/x``
            finite.  The pool's pole exclusion is what guarantees no argument starts on one.
            """

            current = argument
            residue = mp.mpc(0)
            while mp.re(current) > 1:
                current -= 1
                if abs(current) < guard:
                    raise SparseRegionError("digamma shift landed on a pole")
                residue += coefficient / current
            while mp.re(current) <= 0:
                if abs(current) < guard:
                    raise SparseRegionError("digamma shift landed on a pole")
                residue -= coefficient / current
                current += 1
            return current, residue

        def rank(value: mp.mpc) -> tuple[mp.mpf, mp.mpf]:
            return (mp.re(value), mp.im(value))

        for coefficient, argument in terms:
            # The orbit of an argument under the two exact rules -- shift by integers and
            # x <-> 1 - x -- is what must be collapsed to a single representative, or two
            # constants whose psi terms *are* the same basis element will not be seen to
            # cancel.  Both branches are computed and the smaller representative wins, so the
            # choice is a total order rather than a window that can miss the tie at Re = 1/2.
            direct, direct_residue = strip(coefficient, argument)
            try:
                reflected, reflected_residue = strip(coefficient, 1 - argument)
            except SparseRegionError:
                # ``argument`` is a positive integer, so its reflection sits on a pole of
                # ``psi`` and of ``cot``.  The direct branch is the only representative.
                scalar += direct_residue
                canonical.append((coefficient, direct))
                continue
            if rank(reflected) < rank(direct):
                scalar += reflected_residue
                cot_terms.append((coefficient, 1 - argument))
                canonical.append((coefficient, reflected))
            else:
                scalar += direct_residue
                canonical.append((coefficient, direct))
    return canonical, scalar, cot_terms


def _bucket(terms: Sequence[tuple[mp.mpc, mp.mpc]], dps: int) -> list[tuple[mp.mpc, mp.mpc]]:
    """Group terms by argument value, matched to ``10^-(dps//2)``."""

    buckets: list[list[Any]] = []
    with mp.workdps(dps):
        window = mp.mpf(10) ** (-(dps // 2))
        for coefficient, argument in terms:
            for bucket in buckets:
                if abs(bucket[1] - argument) < window:
                    bucket[0] += coefficient
                    break
            else:
                buckets.append([coefficient, argument])
    return [(bucket[0], bucket[1]) for bucket in buckets]


def digamma_span_residue(
    terms: Sequence[tuple[mp.mpc, mp.mpc]], dps: int
) -> tuple[bool, mp.mpc, dict[str, Any]]:
    """``(psi terms cancel, elementary remainder, report)`` for one canonicalised expansion."""

    with mp.workdps(dps):
        scale = max((abs(coefficient) for coefficient, _ in terms), default=mp.mpf(0))
        if scale == 0:
            return False, mp.mpc(0), {"psi_buckets": 0, "note": "empty expansion"}
        canonical, scalar, cot_terms = canonicalise_digamma_terms(terms, dps)
        buckets = _bucket(canonical, dps)
        threshold = scale * mp.mpf(10) ** (-(dps - 80))
        worst = max((abs(coefficient) for coefficient, _ in buckets), default=mp.mpf(0))
        elementary = scalar
        for coefficient, argument in _bucket(cot_terms, dps):
            elementary += coefficient * mp.pi / mp.tan(mp.pi * argument)
        report = {
            "psi_buckets": len(buckets),
            "largest_residual_coefficient": mp.nstr(worst, 4),
            "cancellation_threshold": mp.nstr(threshold, 4),
            "certificate": (
                f"exact modulus-{DIGAMMA_REFINEMENT_MODULUS} expansion with a numerical "
                f"cancellation certificate at {dps} digits"
            ),
        }
        return bool(worst < threshold), elementary, report


def elementary_collapse(record: Mapping[str, Any], dps: int = 150) -> mp.mpc | None:
    """The member's own value as an elementary expression, when the ``psi`` terms cancel.

    A quadratic whose roots are closed under ``r -> 1 - r`` (that is, ``a = -1``) has its two
    ``psi`` terms carried onto each other by the reflection formula, and the constant collapses
    to ``pi cot`` at an algebraic argument -- an elementary closed form, and so not a discovery.
    Returns the collapsed value, or ``None`` when the ``psi`` terms do not cancel.
    """

    if record["pool_class"] not in SUM_CLASS_NAMES:
        return None
    terms = digamma_expansion(record, dps)
    cancels, elementary, _ = digamma_span_residue(terms, dps)
    return elementary if cancels else None


def attempt_digamma_span(
    hit: Mapping[str, Any], records: Mapping[str, Mapping[str, Any]], dps: int = 300
) -> dict[str, Any]:
    """Does the relation reduce identically in the modulus-12 digamma span?

    A firing here exhibits the relation as a consequence of partial fractions plus the digamma
    recurrence, reflection and multiplication theorems -- the classical toolkit for these sums.
    Two things must hold, not one: the ``psi`` terms must cancel bucket by bucket, **and** what
    is left (the shift residues, the ``pi cot`` terms from reflection, and the anchors) must
    itself vanish.  Requiring only the first would fire on relations that are not even true.

    The expansion is exact; the cancellation is a numerical certificate at ``dps`` digits, and
    is labelled as such.  Firing only ever moves a candidate *out* of the headline, so the
    conservative failure mode is a survivor a human then knocks down.
    """

    names = list(hit["constants"])
    if any(records[name]["pool_class"] not in SUM_CLASS_NAMES for name in names):
        return {
            "fired": False,
            "blocker": "digamma_span_not_defined_for_class",
            "detail": "at least one constant is not a partial-fraction sum",
        }
    terms: list[tuple[mp.mpc, mp.mpc]] = []
    with mp.workdps(dps):
        magnitude = mp.mpf(0)
        for coefficient, name in zip(hit["coefficients"], names, strict=False):
            if coefficient == 0:
                continue
            magnitude += abs(coefficient * mp.mpf(records[name]["value"]))
            for weight, argument in digamma_expansion(records[name], dps):
                terms.append((coefficient * weight, argument))
        if not terms:
            return {"fired": False, "blocker": "empty_expansion", "detail": "no terms"}
        cancels, elementary, report = digamma_span_residue(terms, dps)
        anchors = list(hit["anchors"])
        for coefficient, anchor in zip(hit["coefficients"][len(names) :], anchors, strict=True):
            if coefficient:
                elementary += coefficient * classical_value(anchor)
                magnitude += abs(coefficient * classical_value(anchor))
        remainder_bound = max(magnitude, mp.mpf(1)) * mp.mpf(10) ** (-(dps - 80))
        closes = bool(abs(elementary) < remainder_bound)
        report["elementary_remainder"] = mp.nstr(abs(elementary), 4)
        report["elementary_remainder_bound"] = mp.nstr(remainder_bound, 4)
        if not cancels:
            blocker = "digamma_span_does_not_cancel"
        elif not closes:
            blocker = "elementary_remainder_does_not_vanish"
        else:
            blocker = None
        return {"fired": bool(cancels and closes), "blocker": blocker, "detail": report}


def attempt_gauss_digamma(
    hit: Mapping[str, Any], records: Mapping[str, Mapping[str, Any]]
) -> dict[str, Any]:
    """Every sum-class constant in the relation has only rational roots."""

    names = list(hit["constants"])
    rational: dict[str, list[str]] = {}
    for coefficient, name in zip(hit["coefficients"], names, strict=False):
        if coefficient == 0:
            continue
        record = records[name]
        if record["pool_class"] not in SUM_CLASS_NAMES:
            return {
                "fired": False,
                "blocker": "gauss_digamma_not_defined_for_class",
                "detail": f"{name} is not a partial-fraction sum",
            }
        parameters = record["parameters"]
        roots = polynomial_rational_roots(
            int(parameters["p"]), int(parameters["a"]), int(parameters["b"])
        )
        if roots is None:
            return {
                "fired": False,
                "blocker": "irrational_digamma_argument",
                "detail": f"{name} has an irrational root; Gauss's theorem does not apply",
            }
        rational[name] = [str(root) for root in roots]
    return {"fired": True, "blocker": None, "detail": {"rational_roots": rational}}


def translation_offset(
    left: Mapping[str, Any], right: Mapping[str, Any]
) -> Fraction | None:
    """The exact rational ``d`` with ``right = left + d``, or ``None`` if they are unrelated.

    Translation stays inside the grammar only at degree two: ``P(n + k) = n^2 + (a + 2k) n +
    (k^2 + a k + b)`` has no ``n^{p-1}`` term to spoil, which a cubic or quartic shift would.
    When ``P_right(n) = P_left(n + k)`` and the weight's period divides ``k``, reindexing gives
    ``S_right = S_left - sum_{m=1..k} w(m) / P_left(m)`` -- a finite sum of rationals with no
    zero denominator, because members with a root at a positive integer are excluded from the
    pool in the first place.
    """

    if left["pool_class"] not in SUM_CLASS_NAMES or right["pool_class"] not in SUM_CLASS_NAMES:
        return None
    first, second = left["parameters"], right["parameters"]
    if int(first["p"]) != 2 or int(second["p"]) != 2:
        return None
    modulus = int(first["modulus"])
    weights = [int(item) for item in first["weights"]]
    if int(second["modulus"]) != modulus:
        return None
    if [int(item) for item in second["weights"]] != weights:
        return None
    a, b = int(first["a"]), int(first["b"])
    shifted_a, shifted_b = int(second["a"]), int(second["b"])
    if (shifted_a - a) % 2:
        return None
    k = (shifted_a - a) // 2
    if shifted_b != k * k + a * k + b:
        return None
    if k % modulus:
        return None
    if k == 0:
        return Fraction(0)
    if k > 0:
        head = sum(
            Fraction(weights[(m - 1) % modulus], m * m + a * m + b) for m in range(1, k + 1)
        )
        return -head
    head = sum(
        Fraction(weights[(m - 1) % modulus], m * m + shifted_a * m + shifted_b)
        for m in range(1, -k + 1)
    )
    return head


def attempt_index_translation(
    hit: Mapping[str, Any], records: Mapping[str, Mapping[str, Any]]
) -> dict[str, Any]:
    """Is the relation just a change of summation index, plus a rational head?

    Constants are grouped into translation classes; inside a class every member equals the
    class representative plus an exact rational.  The relation reduces when each class's
    coefficients sum to zero (so the transcendental part cancels identically) **and** the
    leftover rational, including the ``one`` anchor, is exactly zero.  All of it is ``Fraction``
    arithmetic -- no numerics, so the certificate is checkable by hand from the receipt.
    """

    names: list[str] = []
    coefficients: list[int] = []
    for coefficient, name in zip(hit["coefficients"], hit["constants"], strict=False):
        if coefficient == 0:
            continue
        if records[name]["pool_class"] not in SUM_CLASS_NAMES:
            return {
                "fired": False,
                "blocker": "translation_not_defined_for_class",
                "detail": f"{name} is not a partial-fraction sum",
            }
        if int(records[name]["parameters"]["p"]) != 2:
            return {
                "fired": False,
                "blocker": "translation_only_closed_at_degree_two",
                "detail": f"{name} has degree {records[name]['parameters']['p']}",
            }
        names.append(name)
        coefficients.append(int(coefficient))
    if not names:
        return {"fired": False, "blocker": "no_sum_class_constant_in_relation", "detail": {}}

    anchors = list(hit["anchors"])
    anchor_coefficients = list(hit["coefficients"][len(hit["constants"]) :])
    rational = Fraction(0)
    for coefficient, anchor in zip(anchor_coefficients, anchors, strict=True):
        if coefficient == 0:
            continue
        if anchor != "one":
            return {
                "fired": False,
                "blocker": "irrational_anchor_in_relation",
                "detail": f"anchor {anchor} carries coefficient {coefficient}",
            }
        rational += coefficient

    classes: list[dict[str, Any]] = []
    for name, coefficient in zip(names, coefficients, strict=True):
        for group in classes:
            offset = translation_offset(records[group["representative"]], records[name])
            if offset is not None:
                group["coefficient_sum"] += coefficient
                group["members"][name] = str(offset)
                rational += coefficient * offset
                break
        else:
            classes.append(
                {
                    "representative": name,
                    "coefficient_sum": coefficient,
                    "members": {name: "0"},
                }
            )
    detail = {
        "translation_classes": [
            {
                "representative": group["representative"],
                "coefficient_sum": group["coefficient_sum"],
                "offsets_from_representative": group["members"],
            }
            for group in classes
        ],
        "rational_residue": str(rational),
    }
    if any(group["coefficient_sum"] != 0 for group in classes):
        return {
            "fired": False,
            "blocker": "translation_classes_do_not_cancel",
            "detail": detail,
        }
    if rational != 0:
        return {
            "fired": False,
            "blocker": "translation_rational_residue_does_not_vanish",
            "detail": detail,
        }
    return {"fired": True, "blocker": None, "detail": detail}


def attempt_member_wise(
    hit: Mapping[str, Any], records: Mapping[str, Mapping[str, Any]]
) -> dict[str, Any]:
    """Every constant in the relation already reduced to the classical basis."""

    forms: dict[str, str] = {}
    for coefficient, name in zip(hit["coefficients"], hit["constants"], strict=False):
        if coefficient == 0:
            continue
        status = records[name].get("catalogued_status") or {}
        if not status.get("reduces_to_classical_basis"):
            return {
                "fired": False,
                "blocker": "constant_has_no_classical_closed_form_under_bound",
                "detail": f"{name} did not reduce under the declared bound",
            }
        forms[name] = status.get("classical_closed_form", "")
    return {"fired": True, "blocker": None, "detail": {"closed_forms": forms}}


def attempt_epstein(
    hit: Mapping[str, Any], records: Mapping[str, Mapping[str, Any]]
) -> dict[str, Any]:
    """Every Epstein constant in the relation has class number one, factorisation exhibited."""

    seen: dict[str, Any] = {}
    for coefficient, name in zip(hit["coefficients"], hit["constants"], strict=False):
        if coefficient == 0:
            continue
        record = records[name]
        if record["pool_class"] != "epstein_lattice":
            return {
                "fired": False,
                "blocker": "epstein_factorisation_not_defined_for_class",
                "detail": f"{name} is not an Epstein lattice sum",
            }
        h = int(record["parameters"]["class_number"])
        if h != 1:
            return {
                "fired": False,
                "blocker": "class_number_greater_than_one",
                "detail": f"{name} has h(D) = {h}; the principal form does not factor",
            }
        discriminant = int(record["parameters"]["discriminant"])
        order = int(record["parameters"]["s"])
        with mp.workdps(40):
            closed = epstein_factorisation_value(discriminant, order, 30)
            stored = mp.mpf(record["value"])
            delta = abs(closed - stored) / max(mp.mpf(1), abs(stored))
            if not delta < mp.mpf("1e-20"):
                return {
                    "fired": False,
                    "blocker": "class_number_one_factorisation_did_not_reproduce_the_value",
                    "detail": {name: mp.nstr(delta, 4)},
                }
        units = {-3: 6, -4: 4}.get(discriminant, 2)
        seen[name] = {
            "class_number": h,
            "closed_form": f"{units} * zeta({order}) * L({order}, chi_{discriminant})",
            "relative_agreement": mp.nstr(delta, 4),
        }
    if not seen:
        return {"fired": False, "blocker": "no_epstein_constant_in_relation", "detail": {}}
    return {"fired": True, "blocker": None, "detail": {"factorisations": seen}}


def attempt_epstein_commensurable(
    hit: Mapping[str, Any], records: Mapping[str, Mapping[str, Any]]
) -> dict[str, Any]:
    """Every Epstein constant shares one fundamental discriminant, at the same order ``s``.

    Then all the lattices are commensurable inside a single imaginary quadratic field and the
    classical sublattice/theta identities relate their zeta functions.  A different fundamental
    discriminant means different fields and no such mechanism, so the technique declines.
    """

    fundamentals: set[int] = set()
    orders: set[int] = set()
    detail: dict[str, Any] = {}
    for coefficient, name in zip(hit["coefficients"], hit["constants"], strict=False):
        if coefficient == 0:
            continue
        record = records[name]
        if record["pool_class"] != "epstein_lattice":
            return {
                "fired": False,
                "blocker": "commensurability_not_defined_for_class",
                "detail": f"{name} is not an Epstein lattice sum",
            }
        discriminant = int(record["parameters"]["discriminant"])
        base, conductor = fundamental_discriminant(discriminant)
        fundamentals.add(base)
        orders.add(int(record["parameters"]["s"]))
        detail[name] = {
            "discriminant": discriminant,
            "fundamental_discriminant": base,
            "conductor": conductor,
        }
    if not detail:
        return {"fired": False, "blocker": "no_epstein_constant_in_relation", "detail": {}}
    if len(fundamentals) != 1:
        return {
            "fired": False,
            "blocker": "distinct_fundamental_discriminants",
            "detail": {**detail, "fundamentals": sorted(fundamentals)},
        }
    if len(orders) != 1:
        return {
            "fired": False,
            "blocker": "distinct_orders_s",
            "detail": {**detail, "orders": sorted(orders)},
        }
    return {"fired": True, "blocker": None, "detail": detail}


def attempt_cf_router(
    hit: Mapping[str, Any], records: Mapping[str, Mapping[str, Any]], context: Any
) -> dict[str, Any]:
    """Run cf_proof_router's classical ladder on every continued fraction in the relation."""

    verdicts: dict[str, Any] = {}
    saw_cf = False
    for coefficient, name in zip(hit["coefficients"], hit["constants"], strict=False):
        if coefficient == 0:
            continue
        record = records[name]
        if record["pool_class"] != "cf_unmatched":
            return {
                "fired": False,
                "blocker": "cf_router_not_defined_for_class",
                "detail": f"{name} is not a continued fraction",
            }
        saw_cf = True
        report = route_cf_member(record, context)
        verdicts[name] = {
            "verdict": report["verdict"],
            "technique_that_fired": report.get("technique_that_fired"),
        }
        if report["verdict"] != "PROVED":
            return {
                "fired": False,
                "blocker": "cf_router_missing_technique",
                "detail": {name: verdicts[name], "missing": report.get(
                    "missing_proof_technique"
                )},
            }
    if not saw_cf:
        return {"fired": False, "blocker": "no_continued_fraction_in_relation", "detail": {}}
    return {"fired": True, "blocker": None, "detail": verdicts}


def route_cf_member(record: Mapping[str, Any], context: Any) -> dict[str, Any]:
    """Push one pool continued fraction through ``cf_proof_router.route_candidate``.

    The router asks whether a *declared classical family* covers the continued fraction, so it
    needs a target expression.  Ours have no catalogued closed form, so the target is the
    member's own 200-digit value as an exact sympy ``Float``; the numeric check then passes by
    construction and the three structural techniques (Euler-Minding, Gauss ``2F1``, Pincherle)
    decide the question on the coefficients alone, which is exactly what we want to know.
    """

    parameters = record["parameters"]
    alpha = tuple(int(item) for item in parameters["alpha"])
    beta = tuple(int(item) for item in parameters["beta"])
    candidate = router.RouterCandidate(
        candidate_id=record["constant_id"],
        target_name=record["constant_id"],
        target_expr=sp.Float(record["value"], 210),
        pattern=engine_pattern(alpha, beta),
        wrap=(Fraction(1), Fraction(0), Fraction(0), Fraction(1)),
        cf_value=record["value"][:64],
        formula_text=record["definition"],
        origin="sparse_region_pool",
        prior_verdict="NOT_SCREENED",
        alpha=alpha,
        beta=beta,
    )
    check = router.numeric_check(candidate)
    attempts: list[dict[str, Any]] = []
    for technique in router.TECHNIQUE_ORDER:
        try:
            outcome = router._attempt(context, candidate, technique)
        except Exception as error:  # noqa: BLE001 - a technique that cannot run is not a proof
            # ``equivalence_transformation`` screens against the corpus by *target name*, and a
            # self-generated constant has no catalogued name to screen by.  That is a real
            # limitation of the technique on this input, recorded rather than papered over.
            attempts.append(
                {
                    "technique": technique,
                    "fired": False,
                    "blocker": f"technique_unavailable_for_self_generated_target:{type(error).__name__}",
                }
            )
            continue
        attempts.append({"technique": technique, **outcome["summary"]})
        if outcome["fired"]:
            return {
                "verdict": "PROVED",
                "technique_that_fired": technique,
                "techniques_attempted": attempts,
                "numeric_check": check,
                "cited_theorem": router.TECHNIQUE_CITED_THEOREM[technique],
            }
    blockers = [item["blocker"] for item in attempts if item.get("blocker")]
    return {
        "verdict": "MISSING_TECHNIQUE",
        "technique_that_fired": None,
        "techniques_attempted": attempts,
        "numeric_check": check,
        "missing_proof_technique": (
            blockers[-1] if blockers else "missing_proof_technique:unknown"
        ),
    }


def engine_pattern(alpha: Sequence[int], beta: Sequence[int]) -> Any:
    """A corpus ``CFPattern`` for the engine's polynomial shape."""

    a_poly = Poly(tuple(Fraction(int(item)) for item in alpha))
    b_poly = Poly(tuple(Fraction(int(item)) for item in beta))
    return CFPattern(seq_from_poly(a_poly), drop_index_zero(seq_from_poly(b_poly)))


def attempt_beta_gamma(
    hit: Mapping[str, Any], records: Mapping[str, Mapping[str, Any]]
) -> dict[str, Any]:
    """Every integral in the relation collapses to a Beta value under the grammar."""

    collapsed: dict[str, str] = {}
    saw_integral = False
    for coefficient, name in zip(hit["coefficients"], hit["constants"], strict=False):
        if coefficient == 0:
            continue
        record = records[name]
        if record["pool_class"] != "integral_off_locus":
            return {
                "fired": False,
                "blocker": "beta_reduction_not_defined_for_class",
                "detail": f"{name} is not a family-I integral",
            }
        saw_integral = True
        form = families.canonical_form("I", {**record["parameters"], "prefactor": "1"})
        if form["effective_kernel"] != "one" and Fraction(form["effective_power"]) != 0:
            return {
                "fired": False,
                "blocker": "kernel_does_not_collapse",
                "detail": f"{name} keeps kernel {form['effective_kernel']}",
            }
        collapsed[name] = f"B({form['effective_a']} + 1, {form['effective_b']} + 1)"
    if not saw_integral:
        return {"fired": False, "blocker": "no_integral_in_relation", "detail": {}}
    return {"fired": True, "blocker": None, "detail": {"beta_forms": collapsed}}


def reduce_relation(
    hit: Mapping[str, Any], records: Mapping[str, Mapping[str, Any]], context: Any
) -> dict[str, Any]:
    """Run the declared reduction ladder; the first technique that fires wins."""

    attempts: list[dict[str, Any]] = []
    for technique in REDUCTION_TECHNIQUES:
        if technique == "member_wise_classical_closed_form":
            outcome = attempt_member_wise(hit, records)
        elif technique == "index_translation_with_periodic_weight":
            outcome = attempt_index_translation(hit, records)
        elif technique == "gauss_digamma_rational_arguments":
            outcome = attempt_gauss_digamma(hit, records)
        elif technique == "digamma_span_cancellation":
            outcome = attempt_digamma_span(hit, records)
        elif technique == "epstein_class_number_one_factorisation":
            outcome = attempt_epstein(hit, records)
        elif technique == "epstein_commensurable_lattice_orders":
            outcome = attempt_epstein_commensurable(hit, records)
        elif technique == "cf_proof_router_classical_families":
            outcome = attempt_cf_router(hit, records, context)
        elif technique == "beta_gamma_kernel_collapse":
            outcome = attempt_beta_gamma(hit, records)
        else:  # pragma: no cover - REDUCTION_TECHNIQUES is closed
            raise SparseRegionError(f"unknown reduction technique: {technique}")
        attempts.append({"technique": technique, **outcome})
        if outcome["fired"]:
            return {
                "verdict": "KNOWN_BY_PROOF_FAMILY",
                "technique_that_fired": technique,
                "cited_theorem": REDUCTION_CITED_THEOREM[technique],
                "techniques_attempted": attempts,
            }
    return {
        "verdict": "SURVIVES_CLASSICAL_REDUCTION",
        "technique_that_fired": None,
        "cited_theorem": None,
        "techniques_attempted": attempts,
        "meaning": (
            "true to 400 digits with independently recomputed constants and untouched by the "
            "declared classical ladder. This is NOT a novelty claim: it is an unreviewed "
            "relation, and the honest next step is a human with a literature search."
        ),
    }


