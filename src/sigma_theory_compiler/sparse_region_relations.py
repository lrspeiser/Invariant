def subset_schedule(
    sparse: Sequence[Mapping[str, Any]], *, caps: Mapping[str, int]
) -> list[dict[str, Any]]:
    """The declared, deterministic list of subsets the hunt will test.

    Five schedules.  Every one is a function of the sparse member list and the declared caps --
    no randomness beyond the sealed SHA-256 seed, and no adaptivity, so a rerun produces the
    identical list.  Within a schedule the caps are consumed **round-robin over the blocks**
    rather than block by block: taking the first N in sorted order would spend the whole
    within-class cap on continued fractions and search no integrals at all.
    """

    by_id = {member["constant_id"]: member for member in sparse}
    ordered = sorted(by_id)
    subsets: list[dict[str, Any]] = []

    def valid(ids: Sequence[str]) -> bool:
        return len(set(ids)) == len(ids) and len(ids) >= 2

    def drain(schedule: str, blocks: Sequence[list[tuple[tuple[str, ...], list[str]]]],
              cap: int) -> None:
        """Interleave the blocks' candidate lists until the schedule cap is spent."""

        cursors = [0] * len(blocks)
        emitted = 0
        while emitted < cap:
            progressed = False
            for index, block in enumerate(blocks):
                if emitted >= cap:
                    break
                if cursors[index] >= len(block):
                    continue
                ids, anchors = block[cursors[index]]
                cursors[index] += 1
                progressed = True
                if valid(ids):
                    subsets.append(
                        {
                            "schedule": schedule,
                            "constants": list(ids),
                            "anchors": list(anchors),
                        }
                    )
                    emitted += 1
            if not progressed:
                return

    # Schedule 1 -- the same polynomial across its four twists.  This is where a relation
    # between a plain sum and its character twists would live, and it is also where the
    # digamma multiplication theorem lives, so it exercises the reduction ladder hardest.
    twists: dict[tuple[int, int, int], list[str]] = {}
    for member in sparse:
        parameters = member["parameters"]
        if "p" not in parameters:
            continue
        key = (int(parameters["p"]), int(parameters["a"]), int(parameters["b"]))
        twists.setdefault(key, []).append(member["constant_id"])
    drain(
        "same_polynomial_twists",
        [
            [
                (chosen, ["one"])
                for size in (2, 3, 4)
                for chosen in combinations(sorted(twists[key]), size)
            ]
            for key in sorted(twists)
        ],
        caps["same_polynomial"],
    )

    # Schedule 2 -- pairs and consecutive triples inside a block of fixed (class, p, b) with
    # the linear shift a running.  Neighbouring shifts are the natural place for a recursion.
    blocks: dict[tuple[str, int, int], list[tuple[int, str]]] = {}
    for member in sparse:
        parameters = member["parameters"]
        if "p" not in parameters:
            continue
        key = (member["pool_class"], int(parameters["p"]), int(parameters["b"]))
        blocks.setdefault(key, []).append((int(parameters["a"]), member["constant_id"]))
    windows: list[list[tuple[tuple[str, ...], list[str]]]] = []
    for key in sorted(blocks):
        row = [item for _, item in sorted(blocks[key])]
        windows.append(
            [
                (tuple(row[start : start + size]), ["one"])
                for size in (2, 3)
                for start in range(len(row) - size + 1)
            ]
        )
    drain("shift_window", windows, caps["shift_window"])

    # Schedule 3 -- Epstein tuples at a fixed order, where a relation would be a class-group
    # statement rather than an analytic one.
    epstein: dict[int, list[str]] = {}
    for member in sparse:
        if member["pool_class"] != "epstein_lattice":
            continue
        epstein.setdefault(int(member["parameters"]["s"]), []).append(member["constant_id"])
    drain(
        "epstein_tuple",
        [
            [
                (chosen, ["one"])
                for size in (2, 3)
                for chosen in combinations(sorted(epstein[order]), size)
            ]
            for order in sorted(epstein)
        ],
        caps["epstein"],
    )

    # Schedule 4 -- within-class pairs and triples for the continued-fraction and integral
    # classes, which have no shift parameter to window over.
    structural: dict[str, list[str]] = {}
    for member in sparse:
        if member["pool_class"] in {"cf_unmatched", "integral_off_locus"}:
            structural.setdefault(member["pool_class"], []).append(member["constant_id"])
    drain(
        "within_class",
        [
            [
                (chosen, ["one"])
                for size in (2, 3)
                for chosen in combinations(sorted(structural[name]), size)
            ]
            for name in sorted(structural)
        ],
        caps["structural"],
    )

    # Schedule 5 -- seeded pseudorandom subsets of size 3, 4 and 5 across the whole sparse
    # set, so the hunt is not confined to the structures we guessed at.
    if ordered:
        draws_by_size: list[list[tuple[tuple[str, ...], list[str]]]] = []
        for size in (3, 4, 5):
            draws = deterministic_integers(
                f"{SUBSET_SEED}:{size}", caps["random"] * size, len(ordered)
            )
            anchors = ["one"] if size > 3 else ["one", "pi"]
            draws_by_size.append(
                [
                    (
                        tuple(ordered[draws[start + offset]] for offset in range(size)),
                        anchors,
                    )
                    for start in range(0, len(draws) - size + 1, size)
                ]
            )
        drain("seeded_random", draws_by_size, caps["random"] * 3)

    return subsets


