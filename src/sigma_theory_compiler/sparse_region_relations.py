def _known_sample(reduced: Sequence[Mapping[str, Any]], limit: int = 20) -> list[dict[str, Any]]:
    """A bounded sample of the reduced relations covering every technique that fired."""

    chosen: list[dict[str, Any]] = []
    seen: set[str] = set()
    for item in reduced:
        technique = item["reduction"]["technique_that_fired"]
        if technique not in seen:
            seen.add(technique)
            chosen.append(dict(item))
    for item in reduced:
        if len(chosen) >= limit:
            break
        if item not in chosen:
            chosen.append(dict(item))
    return chosen[:limit]


def _subset_caps(scale: str) -> dict[str, int]:
    if scale == "smoke":
        return {
            "same_polynomial": 200,
            "shift_window": 200,
            "epstein": 60,
            "structural": 60,
            "random": 60,
        }
    return {
        "same_polynomial": 60000,
        "shift_window": 40000,
        "epstein": 4000,
        "structural": 12000,
        "random": 6000,
    }


def run_sparse_regions(
    *,
    config: PoolConfig | None = None,
    scale: str = "full",
    corpus_database: str = "runs/math/prior-art/cf-corpus-v1.sqlite",
    corpus_manifest: str = "runs/math/prior-art/cf-corpus-v1-manifest.json",
    subset_budget_seconds: float | None = None,
) -> dict[str, Any]:
    """Build the pool, map its density, hunt the sparse regions, and seal a receipt."""

    started = time.perf_counter()
    config = config or PoolConfig()
    pool = build_pool(config)
    if not pool["members"]:
        raise SparseRegionError("the pool is empty")
    crosscheck = crosscheck_pool(pool["members"])
    if not crosscheck["control_passed"]:
        raise SparseRegionError("the independent-algorithm cross-check disagreed")

    corpus = load_corpus(corpus_database, corpus_manifest)
    density = build_density_map(pool, corpus)
    records = {member["constant_id"]: member for member in pool["members"]}
    context = router.RouterContext(corpus=corpus)

    sparse = [
        member
        for member in pool["members"]
        if member["catalogued_status"]["is_sparse_member"]
    ]
    caps = _subset_caps(scale)
    subsets = subset_schedule(sparse, caps=caps)

    hunt_started = time.perf_counter()
    with mp.workdps(int(RELATION_HUNT["fit_dps"])):
        values = {member["constant_id"]: mp.mpf(member["value"]) for member in sparse}
    hits: list[dict[str, Any]] = []
    searched = 0
    for subset in subsets:
        if (
            subset_budget_seconds is not None
            and time.perf_counter() - hunt_started > subset_budget_seconds
        ):
            break
        searched += 1
        hit = hunt_subset(subset, values)
        if hit is not None:
            hits.append(hit)
    hunt_seconds = time.perf_counter() - hunt_started

    survivors: list[dict[str, Any]] = []
    discarded: list[dict[str, Any]] = []
    for hit in hits:
        verification = verify_at_400(hit, records)
        entry = {**hit, "relation": render_relation(hit), "verification": verification}
        if verification["survived"]:
            survivors.append(entry)
        else:
            discarded.append(entry)

    reduced: list[dict[str, Any]] = []
    unreduced: list[dict[str, Any]] = []
    for survivor in survivors:
        reduction = reduce_relation(survivor, records, context)
        entry = {
            **survivor,
            "definitions": {
                name: {
                    "definition": records[name]["definition"],
                    "pool_class": records[name]["pool_class"],
                    "parameters": records[name]["parameters"],
                    "value_200dps": records[name]["value"],
                }
                for name in survivor["constants"]
            },
            "reduction": reduction,
        }
        (reduced if reduction["verdict"] == "KNOWN_BY_PROOF_FAMILY" else unreduced).append(entry)

    controls = {
        "planted_known_relation": planted_relation_control(records, context),
        "random_false_relation": false_relation_control(
            records, preferred=[member["constant_id"] for member in sparse]
        ),
        "precision_artifact": precision_artifact_control(records),
        "independent_recomputation": independence_control(records),
        "pool_crosscheck": crosscheck,
    }
    failed = [name for name, item in controls.items() if not item.get("control_passed", False)]
    if failed:
        raise SparseRegionError(f"run-aborting controls failed: {', '.join(sorted(failed))}")

    body: dict[str, Any] = {
        "schema_version": RESULT_SCHEMA,
        "claims": CLAIMS,
        "diagnosis": {
            "prior_campaigns": (
                "1.19e8 continued-fraction ordinals and 3.25e9 series/product/integral "
                "ordinals returned zero new results"
            ),
            "cause": [
                (
                    "targets were the classical constants, whose neighbourhoods are the most "
                    "heavily mined in mathematics"
                ),
                (
                    "the proof step was circular: the reduction techniques ARE the classical "
                    "families, so anything provable was thereby classical"
                ),
                "the grammar was a curated list of families named because they were fruitful",
            ],
            "fix": [
                "Component 1 generates its own targets from declared definitions",
                "Component 2 measures where the corpus and the classical basis are thin",
                "Component 3 hunts only there, and treats failure to reduce as the signal",
            ],
        },
        "pool": {
            key: value for key, value in pool.items() if key not in {"measurement"}
        },
        "density_map": {
            key: value for key, value in density.items() if key not in {"measurement"}
        },
        "relation_hunt": {
            "config": RELATION_HUNT,
            "classicality_config": CLASSICALITY,
            "subset_caps": caps,
            "subset_schedules": sorted({subset["schedule"] for subset in subsets}),
            "subsets_by_schedule": {
                name: sum(1 for subset in subsets if subset["schedule"] == name)
                for name in sorted({subset["schedule"] for subset in subsets})
            },
            "counts": {
                "sparse_members": len(sparse),
                "subsets_declared": len(subsets),
                "subsets_searched": searched,
                "pslq_hits_at_200dps": len(hits),
                "survivors_at_400dps": len(survivors),
                "discarded_as_pslq_artifacts": len(discarded),
                "reduced_known_by_proof_family": len(reduced),
                "survives_classical_reduction": len(unreduced),
            },
            "expected_spurious_hits": (
                "with six terms at a 1e6 coefficient bound the spurious floor is 1e-36 and the "
                "tolerance is 1e-150, so even 1e6 subsets expect 1e6 * 1e-114 false hits"
            ),
            "known_by_technique": {
                name: sum(
                    1
                    for item in reduced
                    if item["reduction"]["technique_that_fired"] == name
                )
                for name in REDUCTION_TECHNIQUES
                if any(
                    item["reduction"]["technique_that_fired"] == name for item in reduced
                )
            },
            "discarded": discarded[:20],
            # One exemplar per technique first, then fill: a sample that shows only the
            # technique that happened to fire earliest would hide what classified the rest.
            "known_by_proof_family": _known_sample(reduced),
        },
        "headline": {
            "relations_surviving_classical_reduction": len(unreduced),
            "relations": unreduced,
            "reading": (
                "a surviving relation is true to 400 digits and untouched by the declared "
                "classical ladder. It is UNREVIEWED, not new. Absence from the corpus "
                "establishes nothing, and every entry needs a human with a literature search."
            ),
        },
        "controls": controls,
        "scope": (
            "Self-generated constants, a measured density map, and a bounded integer-relation "
            "search inside the regions that measurement called sparse. Nothing here is a "
            "proof, and nothing here is a novelty claim."
        ),
    }
    core = canonical_sha256(body)
    body["result_core_sha256"] = core
    body["measurement"] = {
        "elapsed_seconds": format(time.perf_counter() - started, ".3f"),
        "pool_seconds": pool["measurement"]["elapsed_seconds"],
        "density_seconds": density["measurement"]["elapsed_seconds"],
        "hunt_seconds": format(hunt_seconds, ".3f"),
        "subsets_per_second": format(searched / hunt_seconds, ".1f") if hunt_seconds else "0",
    }
    return {**body, "content_sha256": canonical_sha256(body)}


