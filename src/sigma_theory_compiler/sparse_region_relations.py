def validate_receipt(value: Mapping[str, Any], *, replay_members: int = 3) -> None:
    """Seals, claims, count consistency, controls, and a bounded value replay."""

    if value.get("schema_version") != RESULT_SCHEMA:
        raise SparseRegionError("receipt schema changed")
    body = {key: item for key, item in value.items() if key != "content_sha256"}
    if value.get("content_sha256") != canonical_sha256(body):
        raise SparseRegionError("receipt seal changed")
    core_body = {
        key: item
        for key, item in value.items()
        if key not in {"content_sha256", "result_core_sha256", "measurement"}
    }
    if value.get("result_core_sha256") != canonical_sha256(core_body):
        raise SparseRegionError("deterministic core seal changed")
    if value.get("claims") != CLAIMS:
        raise SparseRegionError("claims block changed")

    pool = value["pool"]
    members = pool["members"]
    if pool["counts"]["members"] != len(members):
        raise SparseRegionError("pool member count changed")
    if pool["config_sha256"] != canonical_sha256(pool["config"]):
        raise SparseRegionError("pool config binding changed")
    by_class: dict[str, int] = {}
    for member in members:
        if not member["error_bound"].get("certified"):
            raise SparseRegionError("an uncertified member survived into the pool")
        by_class[member["pool_class"]] = by_class.get(member["pool_class"], 0) + 1
    if pool["counts"]["by_class"] != by_class:
        raise SparseRegionError("pool class histogram changed")

    density = value["density_map"]
    tally: dict[str, list[int]] = {}
    for member in members:
        status = member["catalogued_status"]
        if status is None:
            raise SparseRegionError("a member left the density map with no catalogued status")
        row = tally.setdefault(member["region"], [0, 0, 0])
        row[0] += 1
        row[1] += int(status["reduces_to_classical_basis"])
        row[2] += status["corpus_value_hits"]
    for region in density["regions"]:
        expected = tally.get(region["region"])
        if expected is None:
            raise SparseRegionError(f"density row for an absent region: {region['region']}")
        if [region["members"], region["reduced"], region["corpus_value_hits"]] != expected:
            raise SparseRegionError(f"density counts changed for {region['region']}")
        if region["reduction_fraction"] != f"{expected[1]}/{expected[0]}":
            raise SparseRegionError(f"density fraction changed for {region['region']}")
        sparse = Fraction(expected[1], expected[0]) <= SPARSE_REDUCTION_FRACTION
        if region["verdict"] != ("SPARSE" if sparse else "DENSE"):
            raise SparseRegionError(f"density verdict changed for {region['region']}")
        if sum(region["reduced_by"].values()) != region["reduced"]:
            raise SparseRegionError(f"technique histogram does not close for {region['region']}")

    counts = value["relation_hunt"]["counts"]
    headline = value["headline"]
    if counts["survives_classical_reduction"] != len(headline["relations"]):
        raise SparseRegionError("headline count does not match the headline list")
    if counts["survivors_at_400dps"] != (
        counts["reduced_known_by_proof_family"] + counts["survives_classical_reduction"]
    ):
        raise SparseRegionError("survivor accounting does not close")
    if counts["pslq_hits_at_200dps"] != (
        counts["survivors_at_400dps"] + counts["discarded_as_pslq_artifacts"]
    ):
        raise SparseRegionError("hit accounting does not close")
    by_technique = value["relation_hunt"]["known_by_technique"]
    if sum(by_technique.values()) != counts["reduced_known_by_proof_family"]:
        raise SparseRegionError("the reduction technique histogram does not close")
    if set(by_technique) - set(REDUCTION_TECHNIQUES):
        raise SparseRegionError("a reduction verdict names an undeclared technique")
    sampled = {
        item["reduction"]["technique_that_fired"]
        for item in value["relation_hunt"]["known_by_proof_family"]
    }
    if by_technique and sampled != set(by_technique):
        raise SparseRegionError("the stored sample does not cover every technique that fired")
    for name, control in value["controls"].items():
        if not control.get("control_passed", False):
            raise SparseRegionError(f"receipt records a failed control: {name}")
    for relation in headline["relations"]:
        if relation["reduction"]["verdict"] != "SURVIVES_CLASSICAL_REDUCTION":
            raise SparseRegionError("a reduced relation is sitting in the headline")
        fired = {item["technique"] for item in relation["reduction"]["techniques_attempted"]}
        if fired != set(REDUCTION_TECHNIQUES):
            raise SparseRegionError("a headline relation skipped a declared technique")

    records = {member["constant_id"]: member for member in members}
    for member in members[:replay_members]:
        replayed = recompute_value(member, 60)
        with mp.workdps(60):
            stored = mp.mpf(member["value"])
            if not abs(replayed - stored) / max(mp.mpf(1), abs(stored)) < mp.mpf("1e-45"):
                raise SparseRegionError(f"value replay failed for {member['constant_id']}")
    for relation in headline["relations"][:replay_members]:
        if any(name not in records for name in relation["constants"]):
            raise SparseRegionError("a headline relation names a constant outside the pool")


def write_receipt(result: Mapping[str, Any], output: str) -> None:
    """Write a canonical, immutable receipt."""

    path = Path(output)
    encoded = canonical_json_bytes(result) + b"\n"
    if path.exists() and path.read_bytes() != encoded:
        raise SparseRegionError("refusing to overwrite immutable receipt")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(encoded)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Sparse-region relation discovery over self-generated constants (DG4)."
    )
    parser.add_argument("--output", default="runs/math/sparse-regions/relations-v1.json")
    parser.add_argument("--scale", choices=("full", "smoke"), default="full")
    defaults = PoolConfig()
    parser.add_argument("--shift-box", type=int, default=defaults.shift_box)
    parser.add_argument("--cf-members", type=int, default=defaults.cf_members)
    parser.add_argument("--integral-members", type=int, default=defaults.integral_members)
    parser.add_argument(
        "--epstein-min-discriminant", type=int, default=defaults.epstein_min_discriminant
    )
    parser.add_argument("--hunt-budget-seconds", type=float, default=None)
    parser.add_argument("--database", default="runs/math/prior-art/cf-corpus-v1.sqlite")
    parser.add_argument("--manifest", default="runs/math/prior-art/cf-corpus-v1-manifest.json")
    parser.add_argument("--validate-checked", action="store_true")
    args = parser.parse_args()
    if args.validate_checked:
        validate_receipt(json.loads(Path(args.output).read_text(encoding="utf-8")))
        print(json.dumps({"validated": True, "output": args.output}))
        return 0
    config = PoolConfig(
        shift_box=args.shift_box,
        cf_members=args.cf_members,
        integral_members=args.integral_members,
        epstein_min_discriminant=args.epstein_min_discriminant,
    )
    result = run_sparse_regions(
        config=config,
        scale=args.scale,
        corpus_database=args.database,
        corpus_manifest=args.manifest,
        subset_budget_seconds=args.hunt_budget_seconds,
    )
    write_receipt(result, args.output)
    print(
        json.dumps(
            {
                "pool": result["pool"]["counts"],
                "density": result["density_map"]["counts"],
                "sparse_regions": [
                    row["region"]
                    for row in result["density_map"]["regions"]
                    if row["verdict"] == "SPARSE"
                ],
                "dense_regions": [
                    row["region"]
                    for row in result["density_map"]["regions"]
                    if row["verdict"] == "DENSE"
                ],
                "hunt": result["relation_hunt"]["counts"],
                "headline": result["headline"]["relations_surviving_classical_reduction"],
                "measurement": result["measurement"],
                "output": args.output,
                "content_sha256": result["content_sha256"],
            },
            indent=2,
        )
    )
    return 0


