def _bound_string(dps: int) -> str:
    return f"1e-{dps + BOUND_MARGIN}"


def _certify(low: mp.mpf, high: mp.mpf, dps: int) -> tuple[bool, str]:
    """Dual-precision agreement against the declared bound."""

    with mp.workdps(dps + GUARD_HIGH):
        scale = max(mp.mpf(1), abs(high))
        delta = abs(low - high) / scale
        bound = mp.mpf(10) ** (-(dps + BOUND_MARGIN))
        text = "0e0" if delta == 0 else mp.nstr(delta, 5)
        return bool(mp.isfinite(delta) and delta < bound), text


def _signed_term(coefficient: int, suffix: str) -> str:
    """``' + 3*n'`` / ``' - 3*n'`` / ``''`` -- readable polynomial rendering."""

    if coefficient == 0:
        return ""
    sign = "+" if coefficient > 0 else "-"
    return f" {sign} {abs(coefficient)}{suffix}"


def sum_class_members(config: PoolConfig) -> Iterator[dict[str, Any]]:
    """Every admissible sum-class definition in the declared box, in canonical order."""

    box = config.shift_box
    for spec in SUM_CLASSES:
        for p in config.sum_powers:
            for a in range(-box, box + 1):
                for b in range(-box, box + 1):
                    if not polynomial_is_squarefree(p, a, b):
                        continue
                    if polynomial_positive_integer_roots(p, a, b):
                        continue
                    poly = f"n^{p}{_signed_term(a, '*n')}{_signed_term(b, '')}"
                    yield {
                        "constant_id": f"{spec['pool_class']}:p{p}:a{a}:b{b}",
                        "pool_class": spec["pool_class"],
                        "definition": (
                            f"Sum_{{n>=1}} {spec['summand_prefix']}/({poly})"
                        ),
                        "parameters": {
                            "p": p,
                            "a": a,
                            "b": b,
                            "modulus": spec["modulus"],
                            "weights": list(spec["weights"]),
                            "weight_definition": spec["weight_definition"],
                        },
                        "region": f"{spec['pool_class']}/p={p}",
                    }


def epstein_members(config: PoolConfig) -> Iterator[dict[str, Any]]:
    """One member per (discriminant, order); distinct ``(c, d)`` of equal ``D`` coincide."""

    for discriminant in range(-3, config.epstein_min_discriminant - 1, -1):
        if discriminant % 4 not in (0, 1):
            continue
        a, b, c = principal_form(discriminant)
        h = class_number(discriminant)
        base, conductor = fundamental_discriminant(discriminant)
        # The classical factorisation w * zeta(s) * L(s, chi_D) is a statement about the
        # maximal order.  A class-number-one discriminant that is *not* fundamental sits in a
        # non-maximal order and does not obey it, so it gets its own region rather than being
        # quietly counted as classical.
        if h != 1:
            band = "h=gt1"
        elif conductor == 1:
            band = "h=1_fundamental"
        else:
            band = "h=1_nonfundamental"
        for order in config.epstein_orders:
            yield {
                "constant_id": f"epstein:D{discriminant}:s{order}",
                "pool_class": "epstein_lattice",
                "definition": (
                    f"Sum_{{(m,n) != (0,0)}} 1/({a}*m^2 + {b}*m*n + {c}*n^2)^{order}"
                ),
                "parameters": {
                    "discriminant": discriminant,
                    "form": [a, b, c],
                    "s": order,
                    "class_number": h,
                    "fundamental_discriminant": base,
                    "conductor": conductor,
                },
                "region": f"epstein_lattice/s={order}/{band}",
            }


def cf_members(config: PoolConfig) -> Iterator[dict[str, Any]]:
    """Continued fractions the earlier enumeration computed but matched to nothing.

    The engine's grammar is walked on a declared arithmetic progression of shape indices with
    the identity Moebius wrap.  A shape is admitted only when its depth-``D`` and depth-``2D``
    convergents agree (so the value exists) and it is more than ``1e-25`` from every classical
    target the engine ever aimed at (so it corresponds to no catalogued constant).
    """

    admitted = 0
    step = 0
    with mp.workdps(60):
        targets = [engine.constant_value(name) for name in engine.CF_TARGET_NAMES]
    while admitted < config.cf_members and step < 200 * config.cf_members:
        shape = (config.cf_shape_offset + step * config.cf_shape_stride) % engine.SHAPE_COUNT
        step += 1
        alpha, beta = engine.decode_shape(shape)
        if all(value == 0 for value in beta):
            continue
        try:
            with mp.workdps(60):
                near = engine.cf_value_mp(alpha, beta, config.cf_depth // 4)
                far = engine.cf_value_mp(alpha, beta, config.cf_depth // 2)
        except (ZeroDivisionError, ValueError):
            continue
        with mp.workdps(60):
            if not (mp.isfinite(near) and mp.isfinite(far)):
                continue
            if abs(near - far) > mp.mpf("1e-45"):
                continue
            if abs(far) > mp.mpf("1e12") or abs(far) < mp.mpf("1e-12"):
                continue
            if any(abs(far - target) < mp.mpf("1e-25") for target in targets):
                continue
        admitted += 1
        yield {
            "constant_id": f"cf:shape{shape}",
            "pool_class": "cf_unmatched",
            "definition": (
                "CF(a, b) = a_0 + b_1/(a_1 + b_2/(a_2 + ...)) with "
                f"a_n = {alpha[0]} + {alpha[1]}*n + {alpha[2]}*n^2 and "
                f"b_n = {beta[0]} + {beta[1]}*n + {beta[2]}*n^2"
            ),
            "parameters": {
                "shape_index": shape,
                "alpha": list(alpha),
                "beta": list(beta),
                "depth": config.cf_depth,
                "mobius": [1, 0, 0, 1],
            },
            "region": "cf_unmatched/identity_wrap",
        }


def integral_members(config: PoolConfig) -> Iterator[dict[str, Any]]:
    """Family-I integrals at parameter points off the Beta/zeta locus.

    "Off the locus" is a declared, checkable condition: the kernel must survive the grammar's
    own canonicalisation (so the integral is not secretly a Beta value) and both exponents must
    have denominator 12 after reduction (so it is not a Beta value at integers either).
    """

    admitted = 0
    step = 0
    kernels = [item for item in families.INTEGRAL_KERNELS if item["name"] != "one"]
    powers = [value for value in families.I_POWERS if value != 0]
    while admitted < config.integral_members and step < 400 * config.integral_members:
        index_a = (config.integral_offset + step * config.integral_stride) % families.I_GRID
        index_b = (
            config.integral_offset_b + step * config.integral_stride_b
        ) % families.I_GRID
        kernel = kernels[step % len(kernels)]
        power = powers[(step // len(kernels)) % len(powers)]
        step += 1
        exponent_a = families.I_EXPONENTS[index_a]
        exponent_b = families.I_EXPONENTS[index_b]
        if exponent_a.denominator != 12 or exponent_b.denominator != 12:
            continue
        if not families.integral_converges(exponent_a, exponent_b, kernel["index"], power):
            continue
        form = families.canonical_form(
            "I",
            {
                "a": str(exponent_a),
                "b": str(exponent_b),
                "kernel": kernel["name"],
                "kernel_index": kernel["index"],
                "power": str(power),
                "prefactor": "1",
            },
        )
        if form["effective_kernel"] == "one" or Fraction(form["effective_power"]) == 0:
            continue
        admitted += 1
        yield {
            "constant_id": (
                f"integral:{kernel['name']}:a{exponent_a.numerator}:"
                f"b{exponent_b.numerator}:c{power.numerator}_{power.denominator}"
            ),
            "pool_class": "integral_off_locus",
            "definition": (
                f"Integral_0^1 x^({exponent_a}) * (1-x)^({exponent_b}) * "
                f"({kernel['expr']})^({power}) dx"
            ),
            "parameters": {
                "a": str(exponent_a),
                "b": str(exponent_b),
                "kernel": kernel["name"],
                "kernel_index": kernel["index"],
                "power": str(power),
            },
            "region": f"integral_off_locus/{kernel['name']}",
        }


def recompute_value(record: Mapping[str, Any], dps: int) -> mp.mpf:
    """Recompute a pool constant **from its definition alone**.

    This is the independent path used by the 400-digit re-verification.  It reads
    ``pool_class`` and ``parameters`` and nothing else -- in particular it never reads
    ``value``, which is what makes the cache-corruption control meaningful.
    """

    pool_class = record["pool_class"]
    parameters = record["parameters"]
    if pool_class in {spec["pool_class"] for spec in SUM_CLASSES}:
        value, _ = sum_class_value(
            int(parameters["p"]),
            int(parameters["a"]),
            int(parameters["b"]),
            [int(item) for item in parameters["weights"]],
            int(parameters["modulus"]),
            dps + GUARD_LOW,
        )
        return value
    if pool_class == "epstein_lattice":
        return epstein_value(int(parameters["discriminant"]), int(parameters["s"]), dps)
    if pool_class == "cf_unmatched":
        with mp.workdps(dps + GUARD_LOW):
            return engine.cf_value_mp(
                [int(item) for item in parameters["alpha"]],
                [int(item) for item in parameters["beta"]],
                int(parameters["depth"]),
            )
    if pool_class == "integral_off_locus":
        with mp.workdps(dps + GUARD_LOW):
            return families.integral_value_mp(
                Fraction(parameters["a"]),
                Fraction(parameters["b"]),
                int(parameters["kernel_index"]),
                Fraction(parameters["power"]),
            )
    raise SparseRegionError(f"unknown pool class: {pool_class}")


def _evaluate_with_certificate(
    record: Mapping[str, Any], dps: int
) -> tuple[mp.mpf | None, dict[str, Any]]:
    """Value plus its error certificate, or ``(None, why)`` when the bound fails."""

    pool_class = record["pool_class"]
    parameters = record["parameters"]
    certificate: dict[str, Any] = {"declared_bound": _bound_string(dps)}
    try:
        if pool_class in {spec["pool_class"] for spec in SUM_CLASSES}:
            certificate["method"] = "partial_fraction_digamma_closed_form"
            arguments = (
                int(parameters["p"]),
                int(parameters["a"]),
                int(parameters["b"]),
                [int(item) for item in parameters["weights"]],
                int(parameters["modulus"]),
            )
            low, imaginary = sum_class_value(*arguments, dps + GUARD_LOW)
            high, _ = sum_class_value(*arguments, dps + GUARD_HIGH)
            certificate["certification"] = "dual_precision_agreement"
            with mp.workdps(dps + GUARD_HIGH):
                certificate["imaginary_residual"] = mp.nstr(imaginary, 5)
        elif pool_class == "epstein_lattice":
            certificate["method"] = "ewald_incomplete_gamma_split"
            discriminant = int(parameters["discriminant"])
            order = int(parameters["s"])
            low = epstein_value(discriminant, order, dps + GUARD_LOW - 20)
            high = epstein_value(discriminant, order, dps + GUARD_HIGH - 20, radius_scale=1.3)
            certificate["certification"] = "dual_precision_and_enlarged_truncation_radius"
        elif pool_class == "cf_unmatched":
            certificate["method"] = "convergent_ladder"
            depth = int(parameters["depth"])
            alpha = [int(item) for item in parameters["alpha"]]
            beta = [int(item) for item in parameters["beta"]]
            with mp.workdps(dps + GUARD_HIGH):
                low = engine.cf_value_mp(alpha, beta, depth)
                high = engine.cf_value_mp(alpha, beta, 2 * depth)
            certificate["certification"] = "depth_doubling_agreement"
        elif pool_class == "integral_off_locus":
            certificate["method"] = "tanh_sinh_log_domain_quadrature"
            with mp.workdps(dps + GUARD_LOW):
                low = families.integral_value_mp(
                    Fraction(parameters["a"]),
                    Fraction(parameters["b"]),
                    int(parameters["kernel_index"]),
                    Fraction(parameters["power"]),
                )
            with mp.workdps(dps + GUARD_HIGH):
                high = families.integral_value_mp(
                    Fraction(parameters["a"]),
                    Fraction(parameters["b"]),
                    int(parameters["kernel_index"]),
                    Fraction(parameters["power"]),
                )
            certificate["certification"] = "dual_precision_agreement"
        else:
            raise SparseRegionError(f"unknown pool class: {pool_class}")
    except (ValueError, ZeroDivisionError, ArithmeticError) as error:
        certificate.update({"certified": False, "dropped_reason": f"evaluation failed: {error}"})
        return None, certificate
    if not (mp.isfinite(low) and mp.isfinite(high)):
        certificate.update({"certified": False, "dropped_reason": "non-finite value"})
        return None, certificate
    certified, measured = _certify(low, high, dps)
    certificate["measured_relative_agreement"] = measured
    certificate["certified"] = certified
    if not certified:
        certificate["dropped_reason"] = "dual-precision agreement missed the declared bound"
        return None, certificate
    return high, certificate


def build_pool(config: PoolConfig) -> dict[str, Any]:
    """Component 1: the self-generated constant pool with certified error bounds."""

    started = time.perf_counter()
    generators = (
        ("sum_classes", sum_class_members(config)),
        ("epstein_lattice", epstein_members(config)),
        ("cf_unmatched", cf_members(config)),
        ("integral_off_locus", integral_members(config)),
    )
    members: list[dict[str, Any]] = []
    dropped: list[dict[str, Any]] = []
    for _, generator in generators:
        for record in generator:
            value, certificate = _evaluate_with_certificate(record, config.dps)
            if value is None:
                dropped.append(
                    {
                        "constant_id": record["constant_id"],
                        "pool_class": record["pool_class"],
                        "reason": certificate.get("dropped_reason", "uncertified"),
                    }
                )
                continue
            with mp.workdps(config.dps + GUARD_HIGH):
                rendered = mp.nstr(value, config.dps, strip_zeros=False)
            members.append(
                {
                    **record,
                    "value_dps": config.dps,
                    "value": rendered,
                    "error_bound": certificate,
                    "catalogued_status": None,
                }
            )
    by_class: dict[str, int] = {}
    for member in members:
        by_class[member["pool_class"]] = by_class.get(member["pool_class"], 0) + 1
    return {
        "config": config.as_json(),
        "config_sha256": canonical_sha256(config.as_json()),
        "members": members,
        "dropped": dropped,
        "counts": {
            "members": len(members),
            "dropped": len(dropped),
            "by_class": dict(sorted(by_class.items())),
        },
        "error_bound_methods": {
            "zeta_shift/alternating_shift/character_mod3_shift/character_mod4_shift": (
                "partial-fraction digamma closed form evaluated at dps+30 and dps+70; the two "
                f"must agree to {_bound_string(config.dps)} relative, and the imaginary "
                "residual (zero in exact arithmetic) is recorded"
            ),
            "epstein_lattice": (
                "Ewald/incomplete-gamma split evaluated at two precisions and two truncation "
                f"radii (1.0x and 1.3x); the two must agree to {_bound_string(config.dps)}"
            ),
            "cf_unmatched": (
                "depth-D against depth-2D convergents at dps+70; the two must agree to "
                f"{_bound_string(config.dps)}"
            ),
            "integral_off_locus": (
                "tanh-sinh in the log domain at dps+30 and dps+70; the two must agree to "
                f"{_bound_string(config.dps)}"
            ),
        },
        "measurement": {"elapsed_seconds": format(time.perf_counter() - started, ".3f")},
    }


def crosscheck_pool(members: Sequence[Mapping[str, Any]], stride: int = 25) -> dict[str, Any]:
    """Independent-algorithm cross-check of a declared sample of the sum classes."""

    sum_class_names = {spec["pool_class"] for spec in SUM_CLASSES}
    checked: list[dict[str, Any]] = []
    failures = 0
    candidates = [item for item in members if item["pool_class"] in sum_class_names]
    for member in candidates[::stride]:
        parameters = member["parameters"]
        independent = sum_class_crosscheck(
            int(parameters["p"]),
            int(parameters["a"]),
            int(parameters["b"]),
            [int(item) for item in parameters["weights"]],
            int(parameters["modulus"]),
        )
        with mp.workdps(60):
            stored = mp.mpf(member["value"])
            delta = abs(stored - independent) / max(mp.mpf(1), abs(stored))
            agrees = bool(delta < mp.mpf("1e-25"))
            checked.append(
                {
                    "constant_id": member["constant_id"],
                    "relative_difference": "0e0" if delta == 0 else mp.nstr(delta, 4),
                    "agrees": agrees,
                }
            )
        failures += int(not agrees)
    return {
        "method": (
            "head terms plus a Hurwitz-zeta tail expansion -- no digamma, no partial "
            "fractions, a different truncation argument"
        ),
        "sample_stride": stride,
        "sampled": len(checked),
        "agreement_digits": 25,
        "failures": failures,
        "sample": checked[:12],
        "control_passed": failures == 0,
    }


